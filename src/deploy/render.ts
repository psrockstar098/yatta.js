// src/deploy/render.ts — the Render adapter for `yatta deploy`.
//
// Mode: native. Render builds the Bun app itself from the Git push — no
// Dockerfile, no image registry. The Blueprint file (render.yaml) declares
// the service, and the check-only workflow supplies the CI checks that the
// Blueprint's autoDeployTrigger waits on.
//
// Every field below was checked against Render's official Blueprint YAML
// reference before writing: `type: web`, `runtime: node` (Render has no
// separate `bun` runtime value — Bun is preinstalled in the JavaScript
// runtime, so the build/start commands simply use `bun`),
// `autoDeployTrigger: checksPass` (deploy only if the linked branch's CI
// checks pass), `healthCheckPath`, and the `disk` block (name, mountPath,
// sizeGB). Fields the reference does not support are not invented here:
// `numInstances` is omitted because Render defaults a new service to 1
// and forbids scaling a service with an attached disk anyway; `plan` is
// omitted because Render defaults a new web service to 0.5c-512mb; `branch`
// is omitted because a same-repo service uses the Blueprint's branch.
//
// What this adapter deliberately does NOT do: create the Blueprint. A
// render.yaml sitting in a repo deploys nothing until the developer links
// it (Dashboard → New → Blueprint); the CLI prints that step after
// configuring.

import type {
  DeployAdapter,
  DeployManifest,
  GeneratedFile,
  HealthcheckConfig,
  ProjectInfo,
  RollbackCapabilities,
  SecretDefinition,
  StorageCapabilities,
  ValidationResult,
} from "./types";
import { DEPLOY_TEMPLATE_VERSION } from "./types";

/** Disk names stay in [a-zA-Z0-9_-]; the service name keeps the app name as-is. */
function diskName(project: ProjectInfo): string {
  const safe = project.name.replace(/[^a-zA-Z0-9_-]/g, "-").replace(/-+/g, "-") || "yatta";
  return `${safe}-data`;
}

function blueprint(project: ProjectInfo): string {
  return [
    `# Generated by \`yatta deploy --platform render\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# You own this file: edit it, and re-running deploy will refuse to",
    "# overwrite your edits (it reports the conflict instead).",
    "#",
    "# Committing this file alone deploys nothing: link it in Render",
    "# (Dashboard → New → Blueprint) so Render syncs the service below.",
    "# On every push to the branch, the check workflow runs first and",
    "# Render deploys only after its checks pass (autoDeployTrigger:",
    "# checksPass). If no checks are reported at all, Render deploys",
    "# nothing — keep the check workflow on the branch.",
    "#",
    "# Runtime is `node`, not `bun`: Render has no separate `bun` runtime",
    "# value, but Bun is preinstalled in the JavaScript runtime, so the",
    "# build and start commands below just use `bun`.",
    "#",
    "# No `plan` is set: Render defaults a new web service to 0.5c-512mb.",
    "# Persistent disks require a paid plan, so the free tier cannot use",
    "# this file. A service with a persistent disk also does not get",
    "# zero-downtime deploys on Render.",
    "",
    "services:",
    "  - type: web",
    `    name: ${project.name}`,
    "    runtime: node",
    "    buildCommand: bun install",
    `    startCommand: bun ${project.entry}`,
    "    healthCheckPath: /health/z",
    "    autoDeployTrigger: checksPass",
    "    envVars:",
    "      - key: NODE_ENV",
    "        value: production",
    "    disk:",
    `      name: ${diskName(project)}`,
    "      mountPath: /data",
    "      sizeGB: 1",
    "",
    "# SQLite lives on the disk above. Point the app's database path at",
    "# /data (change mountPath if the app stores SQLite elsewhere) and keep",
    "# instances at 1: Render forbids scaling a service with an attached",
    "# disk, which is exactly what SQLite needs.",
    "",
  ].join("\n");
}

function workflow(manifest: DeployManifest): string {
  return [
    `# Generated by \`yatta deploy --platform render\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# Check only: typecheck + tests. This workflow deploys nothing —",
    "# Render deploys from the GitHub push once these checks pass,",
    "# because the Blueprint sets autoDeployTrigger: checksPass.",
    "#",
    "# NOTE: actions below are tag-pinned. Pin each one to its full commit SHA",
    "# before relying on this workflow in production; `yatta deploy doctor`",
    "# warns while any action is still tag-pinned.",
    "",
    "name: Check",
    "",
    "on:",
    "  push:",
    `    branches: [${manifest.deployment.branch}]`,
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Check out",
    "        uses: actions/checkout@v4",
    "      - name: Set up Bun",
    "        uses: oven-sh/setup-bun@v2",
    "      - name: Install dependencies",
    "        run: bun install",
    "      - name: Typecheck",
    "        run: bun x tsc --noEmit",
    "      - name: Test",
    "        run: bun test",
    "",
  ].join("\n");
}

export const renderAdapter: DeployAdapter = {
  id: "render",
  label: "Render",

  getDeploymentMode: () => "native",

  getRequiredSecrets(_manifest: DeployManifest): SecretDefinition[] {
    // The check workflow needs nothing beyond the automatic GITHUB_TOKEN.
    // Render deploys through its GitHub App connection, set up in the
    // dashboard when the Blueprint is linked — no repo secret for Yatta.
    return [];
  },

  getPersistentStorage(): StorageCapabilities {
    return {
      kind: "volume",
      mountPath: "/data",
      singleInstance: true,
      backup:
        "No backup is configured by this adapter — enable Render's disk snapshots in the dashboard, and still test an application-level backup before schema changes.",
    };
  },

  getHealthcheckConfig(): HealthcheckConfig {
    return { path: "/health/z", kind: "liveness" };
  },

  getRollbackCapabilities(): RollbackCapabilities {
    return {
      kind: "platform-deployment",
      detail: "Redeploy a previous deploy from the Render dashboard.",
    };
  },

  validate(project: ProjectInfo): ValidationResult {
    const errors: string[] = [];
    const warnings: string[] = [];
    if (!project.entry) errors.push("No server entrypoint found.");
    warnings.push(
      "Committing render.yaml alone deploys nothing — link it in Render (Dashboard → New → Blueprint) so the service is created from it.",
    );
    warnings.push(
      "Persistent disks require a paid plan — the free tier cannot use this file. No plan is set here, so Render defaults a new web service to 0.5c-512mb.",
    );
    warnings.push(
      "A service with a persistent disk does not get zero-downtime deploys on Render.",
    );
    warnings.push(
      "autoDeployTrigger: checksPass deploys only when the branch's CI checks pass — and deploys nothing at all if no checks are reported, so keep the check workflow on the branch.",
    );
    return { ok: errors.length === 0, errors, warnings };
  },

  generate(project: ProjectInfo, manifest: DeployManifest): GeneratedFile[] {
    return [
      { path: "render.yaml", content: blueprint(project) },
      { path: ".github/workflows/deploy.yml", content: workflow(manifest) },
    ];
  },
};
