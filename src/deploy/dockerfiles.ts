// src/deploy/dockerfiles.ts — the shared Bun Dockerfile for adapters that
// ship a container image (Docker, Northflank). One builder, so the image
// every adapter produces is the same image: multi-stage Bun, frozen
// install when a lockfile exists, liveness healthcheck on /health/z, and a
// /data volume for durable SQLite. The platform label in the header is the
// only per-adapter difference.

import { DEPLOY_TEMPLATE_VERSION } from "./types";

export function bunDockerfile(platform: string, entry: string): string {
  return [
    `# Generated by \`yatta deploy --platform ${platform}\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# You own this file: edit it, and re-running deploy will refuse to",
    "# overwrite your edits (it reports the conflict instead).",
    "",
    "FROM oven/bun:1 AS build",
    "WORKDIR /app",
    "COPY package.json bun.lock* ./",
    "# Frozen install when a lockfile exists, plain install otherwise.",
    "RUN bun install --frozen-lockfile || bun install",
    "COPY . .",
    "",
    "FROM oven/bun:1 AS runtime",
    "WORKDIR /app",
    "COPY --from=build /app ./",
    "ENV NODE_ENV=production PORT=3000",
    "EXPOSE 3000",
    "# Durable data lives here. Mount a volume at /data on the host and point",
    "# the app's database path at it; a container filesystem alone is not storage.",
    'VOLUME ["/data"]',
    "# Liveness only: /health/z never touches a subsystem, so a failing app",
    "# dependency cannot mask a dead process (or vice versa).",
    "HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\",
    "  CMD [\"bun\", \"-e\", \"fetch('http://127.0.0.1:'+(process.env.PORT||3000)+'/health/z').then(r=>{if(!r.ok)process.exit(1)}).catch(()=>process.exit(1))\"]",
    `CMD ["bun", "${entry}"]`,
    "",
  ].join("\n");
}

export function dockerignore(platform: string): string {
  return [
    `# Generated by \`yatta deploy --platform ${platform}\`.`,
    "node_modules",
    ".git",
    ".DS_Store",
    "*.log",
    "tmp",
    "coverage",
    "",
  ].join("\n");
}
