// src/deploy/northflank.ts — the Northflank adapter for `yatta deploy`.
//
// Mode: github-actions, following Northflank's own guide and the
// first-party action's action.yml (both read before writing this file):
// CI checks the code, builds ONE immutable image tagged with the commit
// SHA, pushes it to GHCR, and northflank/deploy-to-northflank@v1 deploys
// that exact image to an existing service. Rollback is redeploying the
// previous SHA tag through the same action.
//
// The action's inputs are exactly: northflank-api-key (required),
// project-id (required), service-id or job-id, image-path (required),
// credentials-id (optional), northflank-api-host (default
// https://api.northflank.com). The project and service IDs are the
// developer's own — they do not exist until the developer creates the
// project and service in Northflank — so this adapter references them as
// repo secrets (NORTHFLANK_PROJECT_ID, NORTHFLANK_SERVICE_ID) instead of
// inventing placeholder IDs. credentials-id "github" follows Northflank's
// guide for GHCR images: Northflank needs GHCR pull credentials configured
// under that name.
//
// What this adapter deliberately does NOT do: create the Northflank
// project, service, volume, or domain. Those are one-time dashboard steps;
// the CLI prints them after configuring.

import { bunDockerfile, dockerignore } from "./dockerfiles";
import type {
  DeployAdapter,
  DeployManifest,
  GeneratedFile,
  HealthcheckConfig,
  ProjectInfo,
  RollbackCapabilities,
  SecretDefinition,
  StorageCapabilities,
  ValidationResult,
} from "./types";
import { DEPLOY_TEMPLATE_VERSION } from "./types";

function workflow(manifest: DeployManifest): string {
  return [
    `# Generated by \`yatta deploy --platform northflank\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# One commit, one image: CI checks the code, builds the commit-SHA",
    "# image, pushes it to GHCR, and the Deploy to Northflank action",
    "# deploys that exact image to your service. Rollback is redeploying",
    "# the previous SHA tag through the same action.",
    "#",
    "# Before the first push, set three repo secrets: NORTHFLANK_API_KEY",
    "# (a Northflank API token), NORTHFLANK_PROJECT_ID, and",
    "# NORTHFLANK_SERVICE_ID (from the project and service you create in",
    "# Northflank). Also configure GHCR pull credentials in Northflank",
    "# under the name \"github\" — the deploy step below references them.",
    "#",
    "# NOTE: actions below are tag-pinned. Pin each one to its full commit SHA",
    "# before relying on this workflow in production; `yatta deploy doctor`",
    "# warns while any action is still tag-pinned.",
    "",
    "name: Deploy (Northflank)",
    "",
    "on:",
    "  push:",
    `    branches: [${manifest.deployment.branch}]`,
    "",
    "concurrency:",
    "  group: production-deploy",
    "  cancel-in-progress: false",
    "",
    "permissions:",
    "  contents: read",
    "  packages: write",
    "",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Check out",
    "        uses: actions/checkout@v4",
    "      - name: Set up Bun",
    "        uses: oven-sh/setup-bun@v2",
    "      - name: Install dependencies",
    "        run: bun install",
    "      - name: Typecheck",
    "        run: bun x tsc --noEmit",
    "      - name: Test",
    "        run: bun test",
    "",
    "  deploy:",
    "    needs: check",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Check out",
    "        uses: actions/checkout@v4",
    "      - name: Log in to GHCR",
    "        uses: docker/login-action@v3",
    "        with:",
    "          registry: ghcr.io",
    "          username: ${{ github.actor }}",
    "          password: ${{ secrets.GITHUB_TOKEN }}",
    "      - name: Build and push image",
    "        uses: docker/build-push-action@v6",
    "        with:",
    "          context: .",
    "          push: true",
    "          tags: |",
    "            ghcr.io/${{ github.repository }}:${{ github.sha }}",
    "            ghcr.io/${{ github.repository }}:latest",
    "      - name: Deploy to Northflank",
    "        uses: northflank/deploy-to-northflank@v1",
    "        with:",
    "          northflank-api-key: ${{ secrets.NORTHFLANK_API_KEY }}",
    "          project-id: ${{ secrets.NORTHFLANK_PROJECT_ID }}",
    "          service-id: ${{ secrets.NORTHFLANK_SERVICE_ID }}",
    "          image-path: ghcr.io/${{ github.repository }}:${{ github.sha }}",
    "          credentials-id: github",
    "",
  ].join("\n");
}

export const northflankAdapter: DeployAdapter = {
  id: "northflank",
  label: "Northflank",

  getDeploymentMode: () => "github-actions",

  getRequiredSecrets(_manifest: DeployManifest): SecretDefinition[] {
    // The API key is a genuine secret. The project and service IDs are the
    // developer's own identifiers, referenced as secrets so the generated
    // workflow ships no placeholder IDs that would fail on first push.
    return [
      {
        name: "NORTHFLANK_API_KEY",
        required: true,
        description: "A Northflank API token (never your account password).",
      },
      {
        name: "NORTHFLANK_PROJECT_ID",
        required: true,
        description: "ID of the Northflank project the service belongs to.",
      },
      {
        name: "NORTHFLANK_SERVICE_ID",
        required: true,
        description: "ID of the Northflank service to deploy to.",
      },
    ];
  },

  getPersistentStorage(): StorageCapabilities {
    return {
      kind: "volume",
      mountPath: "/data",
      singleInstance: true,
      backup:
        "No backup is configured by this adapter — a Northflank volume is not a backup. Snapshot the volume on a schedule outside this workflow.",
    };
  },

  getHealthcheckConfig(): HealthcheckConfig {
    return { path: "/health/z", kind: "liveness" };
  },

  getRollbackCapabilities(): RollbackCapabilities {
    return {
      kind: "image-tag",
      detail:
        "Redeploy the previous commit-SHA image tag through the Deploy to Northflank action; the image itself never changes after it is built.",
    };
  },

  validate(project: ProjectInfo): ValidationResult {
    const errors: string[] = [];
    if (!project.entry) errors.push("No server entrypoint found.");
    // The image builds in CI, so a missing local `docker` is not a warning
    // here (unlike the Docker adapter, where local builds are the point).
    return { ok: errors.length === 0, errors, warnings: [] };
  },

  generate(project: ProjectInfo, manifest: DeployManifest): GeneratedFile[] {
    return [
      { path: "Dockerfile", content: bunDockerfile("northflank", project.entry) },
      { path: ".dockerignore", content: dockerignore("northflank") },
      { path: ".github/workflows/deploy.yml", content: workflow(manifest) },
    ];
  },
};
