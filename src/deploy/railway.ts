// src/deploy/railway.ts — the Railway adapter for `yatta deploy`.
//
// Mode: native. Railway's own builder (Railpack) builds the Bun app from
// the GitHub push; nothing is built in CI. The check-only workflow runs
// typecheck + tests, and the service deploys only after it passes —
// enable "Wait for CI" on the service dashboard, because that gate is a
// dashboard setting, not something this adapter can set in a file.
//
// IMPORTANT, verified against Railway's docs in November 2026:
// railway.json / railway.toml (Config as Code) are DEPRECATED and stop
// being read on 2026-12-01 — new services cannot opt into them at all.
// This adapter therefore generates .railway/railway.ts (Infrastructure as
// Code, TypeScript, generally available) instead. Railway never reads that
// file during deploys: it is evaluated by the Railway CLI via
// `railway config plan` / `railway config apply`, which is why the
// generated file needs the `railway` package installed in the project and
// CLI 5.42.1+. The DSL shapes below (defineRailway, github(), service()
// with build/start/healthcheck/replicas/volumeMounts, volume(), project())
// come from the railway 3.x SDK's own types and README, not from memory.
//
// What this adapter deliberately does NOT do: create the Railway project,
// the public domain, or the card on file. Those are one-time dashboard
// steps the developer owns; the CLI prints them after configuring.

import { spawnSync } from "node:child_process";

import { gitRemote } from "./git";
import type {
  DeployAdapter,
  DeployManifest,
  GeneratedFile,
  HealthcheckConfig,
  ProjectInfo,
  RollbackCapabilities,
  SecretDefinition,
  StorageCapabilities,
  ValidationResult,
} from "./types";
import { DEPLOY_TEMPLATE_VERSION } from "./types";

function railwayCliAvailable(): boolean {
  try {
    return spawnSync("railway", ["--version"], { encoding: "utf8" }).status === 0;
  } catch {
    return false;
  }
}

/**
 * "owner/repo" from a GitHub remote, or null for a non-GitHub remote.
 * Accepts https://github.com/owner/repo(.git), ssh://git@github.com/owner/repo,
 * and git@github.com:owner/repo — anything else is not a Railway GitHub
 * source and must not be guessed into one.
 */
function parseGithubRepo(remote: string | null): string | null {
  if (!remote) return null;
  const match =
    remote.match(/^https:\/\/github\.com\/([^/\s]+\/[^/\s]+?)(?:\.git)?\/?$/) ??
    remote.match(/^ssh:\/\/git@github\.com\/([^/\s]+\/[^/\s]+?)(?:\.git)?\/?$/) ??
    remote.match(/^git@github\.com:([^/\s]+\/[^/\s]+?)(?:\.git)?\/?$/);
  return match ? match[1]! : null;
}

/** Volume names stay in [a-zA-Z0-9_-]; the service/project names keep the app name as-is. */
function volumeName(project: ProjectInfo): string {
  const safe = project.name.replace(/[^a-zA-Z0-9_-]/g, "-").replace(/-+/g, "-") || "yatta";
  return `${safe}-data`;
}

function railwayTs(project: ProjectInfo): string {
  const repo = parseGithubRepo(gitRemote(project.root));
  const sourceLine = repo
    ? `    source: github("${repo}"),`
    : "    // No GitHub remote was found when this file was generated, so no\n    // source is declared. Add `source: github(\"owner/repo\")` after pushing\n    // to GitHub, or the file manages settings without declaring a source.";
  return [
    `// Generated by \`yatta deploy --platform railway\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "// You own this file: edit it, and re-running deploy will refuse to",
    "// overwrite your edits (it reports the conflict instead).",
    "//",
    "// Railway reads this file ONLY through the CLI — `railway config plan`",
    "// previews, `railway config apply` applies — never during deploys.",
    "// Deploys still come from GitHub pushes; enable Wait for CI on the",
    "// service dashboard so a push deploys only after the check workflow",
    "// passes. Do NOT add railway.json / railway.toml: they are deprecated",
    "// and stop being read on 2026-12-01.",
    "",
    `import { defineRailway, github, project, service, volume } from "railway/iac";`,
    "",
    "export default defineRailway(() => {",
    `  const data = volume("${volumeName(project)}");`,
    `  const web = service("${project.name}", {`,
    sourceLine,
    '    build: { builder: "RAILPACK" },',
    `    start: "bun ${project.entry}",`,
    '    healthcheck: "/health/z",',
    "    replicas: 1,",
    '    // One instance only: SQLite lives on this volume, and two writers',
    '    // would corrupt it. Point the app\'s database path at /data (change',
    "    // the key if the app stores SQLite elsewhere).",
    '    volumeMounts: { "/data": data },',
    '    env: { NODE_ENV: "production" },',
    "  });",
    "",
    `  return project("${project.name}", { resources: [data, web] });`,
    "});",
    "",
  ].join("\n");
}

function workflow(manifest: DeployManifest): string {
  return [
    `# Generated by \`yatta deploy --platform railway\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# Check only: typecheck + tests. This workflow deploys nothing —",
    "# Railway deploys from the GitHub push once this workflow passes,",
    "# provided Wait for CI is enabled on the service dashboard.",
    "#",
    "# NOTE: actions below are tag-pinned. Pin each one to its full commit SHA",
    "# before relying on this workflow in production; `yatta deploy doctor`",
    "# warns while any action is still tag-pinned.",
    "",
    "name: Check",
    "",
    "on:",
    "  push:",
    `    branches: [${manifest.deployment.branch}]`,
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Check out",
    "        uses: actions/checkout@v4",
    "      - name: Set up Bun",
    "        uses: oven-sh/setup-bun@v2",
    "      - name: Install dependencies",
    "        run: bun install",
    "      - name: Typecheck",
    "        run: bun x tsc --noEmit",
    "      - name: Test",
    "        run: bun test",
    "",
  ].join("\n");
}

export const railwayAdapter: DeployAdapter = {
  id: "railway",
  label: "Railway",

  getDeploymentMode: () => "native",

  getRequiredSecrets(_manifest: DeployManifest): SecretDefinition[] {
    // The check workflow needs nothing beyond the automatic GITHUB_TOKEN.
    // The railwayapp/config plan/apply CI recipe (optional, not generated
    // here) needs a project token as RAILWAY_TOKEN — the developer creates
    // it when they set that recipe up, and Yatta never sees its value.
    return [];
  },

  getPersistentStorage(): StorageCapabilities {
    return {
      kind: "volume",
      mountPath: "/data",
      singleInstance: true,
      backup:
        "No backup is configured by this adapter — enable scheduled volume backups in the dashboard, or set backupSchedules in volumeMounts.",
    };
  },

  getHealthcheckConfig(): HealthcheckConfig {
    return { path: "/health/z", kind: "liveness" };
  },

  getRollbackCapabilities(): RollbackCapabilities {
    return {
      kind: "platform-deployment",
      detail:
        "Redeploy a previous successful Railway deployment from the dashboard; Railway reverts the image and custom variables together.",
    };
  },

  validate(project: ProjectInfo): ValidationResult {
    const errors: string[] = [];
    const warnings: string[] = [];
    if (!project.entry) errors.push("No server entrypoint found.");
    if (!parseGithubRepo(gitRemote(project.root))) {
      warnings.push(
        "No GitHub remote found — the generated file declares no source. Add `source: github(\"owner/repo\")` after pushing to GitHub.",
      );
    }
    if (!railwayCliAvailable()) {
      warnings.push(
        "The `railway` command was not found here, so `railway config plan` / `apply` cannot run on this machine. Generation still works; install the Railway CLI (5.42.1+) or apply from CI.",
      );
    }
    warnings.push(
      "railway.json / railway.toml are deprecated and stop being read on 2026-12-01 — this adapter generates .railway/railway.ts instead, applied with the Railway CLI.",
    );
    warnings.push(
      "Railway requires a card on file even for free/trial use (per its pricing FAQ) — add one in the dashboard if deploys are gated.",
    );
    return { ok: errors.length === 0, errors, warnings };
  },

  generate(project: ProjectInfo, manifest: DeployManifest): GeneratedFile[] {
    return [
      { path: ".railway/railway.ts", content: railwayTs(project) },
      { path: ".github/workflows/deploy.yml", content: workflow(manifest) },
    ];
  },
};
