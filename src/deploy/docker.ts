// src/deploy/docker.ts — the Docker adapter for `yatta deploy`.
//
// Mode: github-actions. CI builds ONE immutable image tagged with the commit
// SHA and pushes it to the developer's own registry; rollback is redeploying
// the previous SHA tag. The platform never builds twice, and Yatta never
// sees a credential: the workflow uses the automatic GITHUB_TOKEN for GHCR,
// or the developer's own Docker Hub secrets for Docker Hub.
//
// What this adapter deliberately does NOT do: pick a host. Docker is the
// container side of deployment — the image it produces runs anywhere a
// Docker host exists (a VPS, Coolify, or a container platform's Docker
// path). The run command the CLI prints after configuring is the honest
// next step, not a pretend deployment.

import { spawnSync } from "node:child_process";

import { bunDockerfile, dockerignore } from "./dockerfiles";
import type {
  DeployAdapter,
  DeployManifest,
  GeneratedFile,
  HealthcheckConfig,
  ProjectInfo,
  RollbackCapabilities,
  SecretDefinition,
  StorageCapabilities,
  ValidationResult,
} from "./types";
import { DEPLOY_TEMPLATE_VERSION } from "./types";

function dockerAvailable(): boolean {
  try {
    return spawnSync("docker", ["--version"], { encoding: "utf8" }).status === 0;
  } catch {
    return false;
  }
}

function registryOf(manifest: DeployManifest): "ghcr" | "dockerhub" {
  return manifest.docker?.registry ?? "ghcr";
}

/**
 * Image reference for the workflow. GHCR uses the repository itself, so no
 * extra secret is needed; Docker Hub needs the developer's own username,
 * which lives in a secret, never in the file.
 */
function imageRef(registry: "ghcr" | "dockerhub"): string {
  return registry === "ghcr"
    ? "ghcr.io/${{ github.repository }}"
    : "docker.io/${{ secrets.DOCKERHUB_USERNAME }}/${{ github.event.repository.name }}";
}

function loginStep(registry: "ghcr" | "dockerhub"): string {
  if (registry === "ghcr") {
    return [
      "      - name: Log in to GHCR",
      "        uses: docker/login-action@v3",
      "        with:",
      "          registry: ghcr.io",
      "          username: ${{ github.actor }}",
      "          password: ${{ secrets.GITHUB_TOKEN }}",
    ].join("\n");
  }
  return [
    "      - name: Log in to Docker Hub",
    "        uses: docker/login-action@v3",
    "        with:",
    "          username: ${{ secrets.DOCKERHUB_USERNAME }}",
    "          password: ${{ secrets.DOCKERHUB_TOKEN }}",
  ].join("\n");
}

function workflow(manifest: DeployManifest): string {
  const registry = registryOf(manifest);
  return [
    `# Generated by \`yatta deploy --platform docker\` (template v${DEPLOY_TEMPLATE_VERSION}).`,
    "# One commit, one image: CI builds the commit-SHA tag and pushes it to",
    "# your registry. Rollback is redeploying the previous SHA tag.",
    "#",
    "# NOTE: actions below are tag-pinned. Pin each one to its full commit SHA",
    "# before relying on this workflow in production; `yatta deploy doctor`",
    "# warns while any action is still tag-pinned.",
    "",
    "name: Deploy (Docker)",
    "",
    "on:",
    "  push:",
    `    branches: [${manifest.deployment.branch}]`,
    "",
    "concurrency:",
    "  group: production-deploy",
    "  cancel-in-progress: false",
    "",
    "permissions:",
    "  contents: read",
    "  packages: write",
    "",
    "jobs:",
    "  build-and-push:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Check out",
    "        uses: actions/checkout@v4",
    loginStep(registry),
    "      - name: Build and push image",
    "        uses: docker/build-push-action@v6",
    "        with:",
    "          context: .",
    "          push: true",
    `          tags: |`,
    `            ${imageRef(registry)}:${"${{ github.sha }}"}`,
    `            ${imageRef(registry)}:latest`,
    "",
  ].join("\n");
}

export const dockerAdapter: DeployAdapter = {
  id: "docker",
  label: "Docker",

  getDeploymentMode: () => "github-actions",

  getRequiredSecrets(manifest: DeployManifest): SecretDefinition[] {
    // GHCR needs nothing beyond the automatic GITHUB_TOKEN. Docker Hub
    // needs the developer's own account secrets, never Yatta's.
    if (registryOf(manifest) !== "dockerhub") return [];
    return [
      {
        name: "DOCKERHUB_USERNAME",
        required: true,
        description: "Your Docker Hub username, for pushing the image.",
      },
      {
        name: "DOCKERHUB_TOKEN",
        required: true,
        description: "A Docker Hub access token (never your account password).",
      },
    ];
  },

  getPersistentStorage(): StorageCapabilities {
    return {
      kind: "volume",
      mountPath: "/data",
      singleInstance: true,
      backup:
        "No backup is configured by this adapter — a volume is not a backup. Snapshot the host volume on a schedule outside this workflow.",
    };
  },

  getHealthcheckConfig(): HealthcheckConfig {
    return { path: "/health/z", kind: "liveness" };
  },

  getRollbackCapabilities(): RollbackCapabilities {
    return {
      kind: "image-tag",
      detail:
        "Redeploy the previous commit-SHA image tag; the image itself never changes after it is built.",
    };
  },

  validate(project: ProjectInfo): ValidationResult {
    const errors: string[] = [];
    const warnings: string[] = [];
    if (!project.entry) errors.push("No server entrypoint found.");
    if (!dockerAvailable()) {
      warnings.push(
        "The `docker` command was not found here, so local `docker build` cannot run on this machine. Generation still works; build in CI or on a Docker host.",
      );
    }
    return { ok: errors.length === 0, errors, warnings };
  },

  generate(project: ProjectInfo, manifest: DeployManifest): GeneratedFile[] {
    return [
      { path: "Dockerfile", content: bunDockerfile("docker", project.entry) },
      { path: ".dockerignore", content: dockerignore("docker") },
      { path: ".github/workflows/deploy.yml", content: workflow(manifest) },
    ];
  },
};
