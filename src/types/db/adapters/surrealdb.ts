// SurrealDB adapter + session (Phase 2 of the multi-database ORM refactor).
//
// Two classes in one file:
//   SurrealDBSession — a DatabaseSession<"async"> over one SurrealDB
//     connection (or one transaction on it). The root session routes every
//     statement through the shared `Surreal` client; a transaction session
//     routes through its `SurrealTransaction`.
//   SurrealDBAdapter — SurrealDBSession plus the adapter-only surface:
//     ready, syncSchema, listTables/listColumns, withMigrationLock,
//     backup/restore, close. It owns the `Surreal` client.
//
// Embedded by default: `mem://` through the Node engine
// (`@surrealdb/node`'s `createNodeEngines()`), so there is no server to
// run. A `ws://`/`wss://` URL is accepted for a remote server (untested —
// no server exists in this environment — and no auth is wired: only
// servers that accept unauthenticated connections work).
//
// `@surrealdb/node` is loaded through `loadSurrealNode()` (a
// computed-specifier `require`), never statically imported: it loads a
// native binding at import time, and a static import breaks standalone
// binaries that never use SurrealDB (see the loader's comment).
//
// ── ID mapping (the decision) ─────────────────────────────────────────────
// The ORM's primary-key column IS the SurrealDB record id. There is no
// separate `id` field stored in the record:
//   - On write, the pk value becomes the record id (`new RecordId(table,
//     value)` in the `id` slot of the CREATE CONTENT object).
//   - On read, the returned `RecordId`'s `.id` part becomes the pk column's
//     value — so an INTEGER pk reads back as a number and a TEXT/UUID pk
//     as a string, and the ORM's `id` round-trips exactly.
//   - `col.id()` (INTEGER AUTOINCREMENT) is served by a per-table sequence
//     `_yatta_seq_<table>` (`DEFINE SEQUENCE ... START 1`, so the first id
//     is 1, like SQLite), consumed inline in the CREATE statement.
//   - `col.uuid()` is generated by Table before insert; if a session-level
//     insert omits it, this adapter generates `crypto.randomUUID()`.
//   - A TEXT pk with no value lets SurrealDB generate a random string id.
//   - An INTEGER pk that is neither auto-increment nor supplied is refused
//     with a plain YattaError (there is nothing sensible to generate).
// A pk column named anything other than `id` (e.g. `userId`) is still the
// record id: no separate field is defined for it, and the adapter maps
// between the column name and SurrealDB's `id` in every statement it
// builds (WHERE, ORDER BY, SELECT list, decode).
//
// ── Type mapping ──────────────────────────────────────────────────────────
// INTEGER -> int, TEXT -> string, REAL -> float, BLOB -> bytes, boolean ->
// bool (native, NOT 0/1), JSON -> string holding JSON text (exactly like
// SQLite: stringified on write, parsed on read), enum -> string with an
// ASSERT `$value IN [...]` clause, createdAt/updatedAt (default
// CURRENT_TIMESTAMP) -> datetime DEFAULT time::now(), decoded back to an
// ISO string. Nullable columns are `option<T>`; a missing value on a
// non-option field is a SurrealDB error, which is the NOT NULL behaviour.
// Tables are SCHEMAFULL, so unknown fields are rejected by the database,
// not silently stored. `references()` is recorded in the schema but NOT
// enforced: SurrealDB has record links, not foreign keys, so
// capabilities.foreignKeys is false and no ON DELETE action runs.
//
// ── Full-text search ──────────────────────────────────────────────────────
// Real BM25, not a substring fallback: one shared analyzer
// (`_yatta_fts`: class tokenizer, lowercase + ascii filters) and one
// `FULLTEXT ANALYZER ... BM25 HIGHLIGHTS` index per searchable column
// (SurrealDB 3.0+ syntax; the pre-3.0 `SEARCH ANALYZER` spelling is a
// parse error on this engine). Queries use the `@@` / `@n@` match
// operator with `search::score(n)`; the returned `rank` is `-score`, so
// it keeps the session contract's convention (smaller = more relevant,
// like FTS5's bm25). The index maintains itself on write, so
// syncSearchRow is a no-op and rebuildSearchIndex runs REBUILD INDEX.
// Note the AdapterCapabilities type has no SurrealDB member for
// fullTextSearch, so this adapter declares "pg_fts": it means "a real
// indexed full-text search with ranking", not "this is Postgres".
//
// ── Transactions ──────────────────────────────────────────────────────────
// `db.beginTransaction()` + commit()/cancel() on the returned
// SurrealTransaction. Verified: uncommitted writes are invisible outside
// the transaction and visible inside it; cancel discards them. Nested
// transactions do not exist (SurrealTransaction has no beginTransaction
// and there is no SAVEPOINT spelling), so a nested transaction() throws
// a clear YattaError instead of pretending. BEGIN/COMMIT as raw query
// text does NOT work across separate query() calls on this SDK — each
// call is its own request — so the adapter never uses that spelling.
//
// ── Backup / restore ──────────────────────────────────────────────────────
// `db.export()` returns the whole database as SurrealQL text (DEFINEs
// plus INSERTs); backup writes that text to a file. Restore removes
// every user table, then `db.import()`s the file — a replay, not a file
// swap: sequences keep their current value (a gap, never a collision)
// and any statement the import cannot apply (e.g. re-defining an
// analyzer that still exists) fails on its own without stopping the
// rest. capabilities.backupRestore is "snapshot", the closest member.
//
// All behaviour here is probe-verified against surrealdb@2.2.2 with
// @surrealdb/node@3.2.0 (embedded engine surrealdb-4.0.1); see the
// probes in /tmp/surreal-probe*.ts (kept out of the repo).

