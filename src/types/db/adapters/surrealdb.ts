/** Shared analyzer for every full-text index this adapter creates. */
const FTS_ANALYZER = "_yatta_fts";
/** Prefix for the per-table auto-increment sequences. */
const SEQ_PREFIX = "_yatta_seq_";

/** Full-text index name for one searchable column (one field per index). */
function ftsIndexName(table: string, column: string): string {
  return `_fts_${table}_${column}`;
}

/** Auto-increment sequence name for one table. */
function sequenceName(table: string): string {
  return `${SEQ_PREFIX}${table}`;
}

/** Column definitions of one table's schema, as a Map. */
function columnsOf(schema: TableSchema): Map<string, ColumnDefinition> {
  return new Map(Object.entries(schema).map(([name, builder]) => [name, builder.def]));
}

/** Searchable column names for one table's schema, in schema order. */
function searchableColumns(schema: TableSchema): string[] {
  return Object.entries(schema)
    .filter(([, builder]) => builder.def.isSearchable)
    .map(([colName]) => colName);
}

/**
 * A table's primary key column, or null when it has none. Mirrors the
 * SQLite adapter: the first declared primary key, else `"id"` when the
 * schema has one.
 */
function pkColumnName(schema: TableSchema): string | null {
  for (const [colName, builder] of Object.entries(schema)) {
    if (builder.def.primaryKey) return colName;
  }
  return "id" in schema ? "id" : null;
}

/** A SurrealQL string literal: single-quoted, backslash-escaped. */
function surqlStringLiteral(value: string): string {
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

/** Plain-identifier check for table/column names (SurrealQL backtick quoting below). */
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

/**
 * Backtick-quotes an identifier after validating it is plain. Reserved
 * words fail bare (a table named `select` is a parse error), so every
 * identifier the adapter interpolates goes through here.
 */
function qIdent(name: string): string {
  if (!IDENT.test(name)) {
    throw new YattaError(
      `"${name}" is not a plain identifier (letters, digits, underscore, not starting with a digit). ` +
        `SurrealDB table and column names used by this adapter must be plain identifiers.`,
    );
  }
  return `\`${name}\``;
}

/** Maps a SurrealDB error onto a YattaError (never the raw SDK error). */
function wrapSurrealError(err: unknown, surql?: string): YattaError {
  if (err instanceof YattaError) return err;
  const e = err as { kind?: unknown; code?: unknown; message?: unknown } | null;
  const message = typeof e?.message === "string" && e.message !== "" ? e.message : String(err);
  const kind = typeof e?.kind === "string" && e.kind !== "" ? `[${e.kind}] ` : "";
  return new YattaError(`${kind}${message}`, surql);
}

/** Whether a value is a SurrealDB RecordId (instanceof, with a constructor-name fallback). */
function isRecordId(value: unknown): value is RecordId {
  if (value instanceof RecordId) return true;
  return (
    typeof value === "object" &&
    value !== null &&
    typeof (value as { constructor?: { name?: unknown } }).constructor?.name === "string" &&
    ((value as { constructor: { name: string } }).constructor.name === "RecordId" ||
      (value as { constructor: { name: string } }).constructor.name.startsWith("RecordId"))
  );
}

/** Whether a value is a SurrealDB DateTime (instanceof, with a constructor-name fallback). */
function isDateTime(value: unknown): value is DateTime {
  if (value instanceof DateTime) return true;
  return (
    typeof value === "object" &&
    value !== null &&
    typeof (value as { constructor?: { name?: unknown } }).constructor?.name === "string" &&
    ((value as { constructor: { name: string } }).constructor.name === "DateTime" ||
      (value as { constructor: { name: string } }).constructor.name.startsWith("DateTime"))
  );
}

/** Whether a column is a createdAt/updatedAt-style datetime column (the CURRENT_TIMESTAMP marker). */
function isDatetimeColumn(def: ColumnDefinition | undefined): boolean {
  return def?.defaultValue === "CURRENT_TIMESTAMP";
}

// ── SurrealDialect ─────────────────────────────────────────────────────────
//
// The session contract requires a SqlDialect + SqlCompiler, but SurrealDB
// is not SQL: no SQL string the compiler could produce is runnable here.
// This dialect answers the two halves the session actually uses —
// encodeParam / decodeValue, via SqlCompiler.serializeValue / decodeRow —
// and refuses every SQL-emitting method with a plain YattaError instead
// of producing a statement that would fail confusingly at the server.
// compileLimitOffset is the one honest exception: LIMIT / START is real
// SurrealQL spelling, shared with the session's own builders.

class SurrealDialect implements SqlDialect {
  readonly name = "surrealdb";
  readonly supportsReturning = true;
  readonly likeCaseInsensitiveByDefault = false;

  quoteIdent(ident: string): string {
    return qIdent(ident);
  }

  placeholder(index1Based: number): string {
    return `$p${index1Based}`;
  }

  mapColumnType(def: ColumnDefinition): string {
    if (isDatetimeColumn(def)) return "datetime";
    // Booleans are stored as INTEGER in the schema (SQLite affinity) but
    // are native bools in SurrealDB.
    if (def.isBoolean) return "bool";
    switch (def.type) {
      case "INTEGER":
        return "int";
      case "TEXT":
        return "string";
      case "REAL":
        return "float";
      case "BLOB":
        return "bytes";
    }
  }

  compileColumnDefault(def: ColumnDefinition): string {
    if (def.defaultValue === null) return "NONE";
    if (def.defaultValue === "CURRENT_TIMESTAMP") return "time::now()";
    if (def.isBoolean) return def.defaultValue ? "true" : "false";
    if (typeof def.defaultValue === "number") return String(def.defaultValue);
    if (typeof def.defaultValue === "object") {
      return surqlStringLiteral(JSON.stringify(def.defaultValue));
    }
    return surqlStringLiteral(String(def.defaultValue));
  }

  compileColumnFragment(): string {
    throw new YattaError(
      "SurrealDB is not SQL: there is no column fragment to compile. " +
        "Schema is applied with DEFINE FIELD by the SurrealDB adapter, not through the SQL compiler.",
    );
  }

  compileCreateTableSql(): string {
    throw new YattaError(
      "SurrealDB is not SQL: there is no CREATE TABLE to compile. " +
        "Schema is applied with DEFINE TABLE by the SurrealDB adapter, not through the SQL compiler.",
    );
  }

  compileAddColumnSql(): string {
    throw new YattaError(
      "SurrealDB is not SQL: there is no ALTER TABLE to compile. " +
        "Schema is applied with DEFINE FIELD by the SurrealDB adapter, not through the SQL compiler.",
    );
  }

  compileIndexSql(): string {
    throw new YattaError(
      "SurrealDB is not SQL: there is no CREATE INDEX to compile. " +
        "Indexes are applied with DEFINE INDEX by the SurrealDB adapter, not through the SQL compiler.",
    );
  }

  compileCreateTableStatements(): [string, ...string[]] {
    throw new YattaError(
      "SurrealDB is not SQL: there is no CREATE TABLE to compile. " +
        "Schema is applied with DEFINE TABLE / DEFINE FIELD by the SurrealDB adapter, not through the SQL compiler.",
    );
  }

  compileLikePredicate(): string {
    // SurrealQL has no LIKE: the session translates contains /
    // startsWith / endsWith / like into string::contains and friends.
    throw new YattaError(
      "SurrealDB has no LIKE operator. The SurrealDB session translates text filters " +
        "into string::contains / string::starts_with / string::ends_with instead.",
    );
  }

  compileOrderNulls(): string {
    return "";
  }

  compileLimitOffset(take: number | undefined, skip: number | undefined): string {
    const limitSql = take !== undefined ? `LIMIT ${take}` : "";
    const startSql = skip !== undefined ? `START ${skip}` : "";
    return [limitSql, startSql].filter(Boolean).join(" ");
  }

  encodeParam(value: unknown, def?: ColumnDefinition): unknown {
    // Driver half of SqlCompiler.serializeValue (mirrors SqliteDialect,
    // with SurrealDB-native answers): booleans stay booleans, JSON stays
    // a JSON string, Dates become ISO strings — except on a datetime
    // column, where the value must be a DateTime for the field to accept
    // it (a plain ISO string binding is rejected: "Expected `datetime`
    // but found '...'").
    if (def?.isBoolean) return value ? true : false;
    if (def?.isJson) {
      return typeof value === "string" ? value : JSON.stringify(value);
    }
    if (isDateTime(value)) return value;
    if (value instanceof Date) {
      return isDatetimeColumn(def) ? new DateTime(value) : value.toISOString();
    }
    if (typeof value === "string" && isDatetimeColumn(def)) {
      return new DateTime(value);
    }
    if (value instanceof Uint8Array) return value;
    if (typeof value === "object" && value !== null) return JSON.stringify(value);
    return value;
  }

  decodeValue(value: unknown, def?: ColumnDefinition): unknown {
    // A record id reads back as the pk value, not the "table:id" string.
    if (isRecordId(value)) return (value as RecordId).id;
    // A datetime reads back as an ISO string, like every other timestamp
    // in the ORM (the server returns nanosecond precision; the string
    // still parses as a date).
    if (isDateTime(value)) return (value as DateTime).toJSON();
    if (def?.isBoolean) {
      return value === null ? null : !!value;
    }
    if (def?.isJson) {
      if (value === null) return null;
      if (typeof value === "string") {
        try {
          return JSON.parse(value);
        } catch {
          /* leave as-is */
        }
      }
      return value;
    }
    if (!def && typeof value === "string" && (value.startsWith("{") || value.startsWith("["))) {
      try {
        return JSON.parse(value);
      } catch {
        /* leave as-is */
      }
    }
    return value;
  }

  compileUpsert(_plan: UpsertPlan): CompiledSql | null {
    // No atomic upsert through the compiler: the session uses the
    // transactional find-first-then-update/insert fallback, the same
    // behaviour as SQLite.
    return null;
  }
}

