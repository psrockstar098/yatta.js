/** Allocates `$pN` binding names for one statement, in order. */
class BindingAllocator {
  private next = 0;
  readonly bindings: Record<string, unknown> = {};

  alloc(value: unknown): string {
    const name = `p${this.next++}`;
    this.bindings[name] = value;
    return `$${name}`;
  }
}

/** A `like` pattern reduced to the one string operation it means, or null when it means nothing the adapter can express. */
type LikeTranslation =
  | { kind: "exact"; text: string }
  | { kind: "contains"; text: string }
  | { kind: "startsWith"; text: string }
  | { kind: "endsWith"; text: string };

/**
 * Reduces a SQLite LIKE pattern to a case-insensitive string operation.
 * SurrealQL has no LIKE and no regex match, so only the shapes the ORM
 * itself generates (and the common hand-written ones) translate: an
 * exact string, `%inner%`, `prefix%`, `%suffix`. A `_` wildcard or an
 * interior `%` has no equivalent and is refused loudly rather than
 * matched approximately.
 */
function translateLike(pattern: string): LikeTranslation {
  // Split on unescaped % / _, honouring backslash escapes.
  const segments: string[] = [];
  let current = "";
  let hasUnderscore = false;
  let i = 0;
  while (i < pattern.length) {
    const ch = pattern[i]!;
    if (ch === "\\" && i + 1 < pattern.length) {
      const next = pattern[i + 1]!;
      if (next === "%" || next === "_" || next === "\\") {
        current += next;
        i += 2;
        continue;
      }
      current += ch;
      i++;
      continue;
    }
    if (ch === "%") {
      segments.push(current);
      current = "";
      i++;
      continue;
    }
    if (ch === "_") {
      hasUnderscore = true;
      current += ch;
      i++;
      continue;
    }
    current += ch;
    i++;
  }
  segments.push(current);

  if (hasUnderscore) {
    throw new YattaError(
      `LIKE pattern "${pattern}" uses the "_" single-character wildcard, which has no equivalent in SurrealQL. ` +
        `Use contains / startsWith / endsWith, or an exact match.`,
    );
  }
  // segments.length - 1 is the number of unescaped % wildcards.
  if (segments.length === 1) return { kind: "exact", text: segments[0]! };
  if (segments.length === 2 && segments[0] === "" && segments[1] !== "") {
    return { kind: "endsWith", text: segments[1]! };
  }
  if (segments.length === 2 && segments[1] === "" && segments[0] !== "") {
    return { kind: "startsWith", text: segments[0]! };
  }
  if (segments.length === 3 && segments[0] === "" && segments[2] === "" && segments[1] !== "") {
    return { kind: "contains", text: segments[1]! };
  }
  throw new YattaError(
    `LIKE pattern "${pattern}" has interior "%" wildcards, which have no equivalent in SurrealQL. ` +
      `Use contains / startsWith / endsWith, or an exact match.`,
  );
}

// ── SurrealDBSession ─────────────────────────────────────────────────────────

/**
 * One SurrealDB session: the root session (over the shared `Surreal`
 * client) or one transaction (over its `SurrealTransaction`). The adapter
 * IS the root session.
 */
export class SurrealDBSession implements DatabaseSession<"async"> {
  readonly capabilities: AdapterCapabilities = SURREALDB_CAPABILITIES;
  /** SurrealDB is not SQL; this dialect only encodes/decodes values (see above). */
  readonly dialect: SqlDialect = surrealDialect;
  /** Driver-neutral compiler over the dialect (value encoding only — no SQL is generated). */
  readonly compiler: SqlCompiler = surrealCompiler;

  constructor(
    protected readonly holder: SurrealHolder,
    /** The transaction executor, or null for the root session (whose queryable is the shared client, created lazily in ensureReady()). */
    private readonly executor: SurrealQueryable | null,
    private readonly inTx: boolean,
    private readonly debug: boolean = false,
  ) {}

  /** The queryable for this session: the transaction executor, or the shared client once connected. */
  protected get queryable(): SurrealQueryable {
    if (this.executor) return this.executor;
    const db = this.holder.db;
    if (!db) throw new YattaError("SurrealDB connection is not ready yet.");
    return db;
  }

  /** The shared client, once ensureReady() has created it. */
  protected requireDb(): Surreal {
    const db = this.holder.db;
    if (!db) throw new YattaError("SurrealDB connection is not ready yet.");
    return db;
  }

  /** Whether this session is currently inside a transaction. */
  get inTransaction(): boolean {
    return this.inTx || this.holder.activeTx > 0;
  }

  /** Lazily connects + selects namespace/database (once, shared by concurrent callers). */
  protected async ensureReady(): Promise<void> {
    if (this.holder.initialized) return;
    if (this.holder.initPromise) return this.holder.initPromise;
    const p = (async (): Promise<void> => {
      if (this.holder.closed) {
        throw new YattaError("SurrealDB connection is closed.");
      }
      try {
        if (!this.holder.db) {
          // The client is created here, not in the constructor: its
          // engines need @surrealdb/node, which only loads through a
          // dynamic import (see loadSurrealNode).
          const node = await loadSurrealNode();
          this.holder.db = new Surreal({
            engines: { ...createRemoteEngines(), ...node.createNodeEngines() },
          });
        }
        const db = this.holder.db;
        await db.connect(this.holder.url);
        await db.use({ namespace: this.holder.namespace, database: this.holder.database });
        // Readiness probe: selecting the namespace/database must work.
        await db.query("INFO FOR DB;");
      } catch (err) {
        throw wrapSurrealError(err);
      }
    })();
    this.holder.initPromise = p;
    try {
      await p;
      this.holder.initialized = true;
    } catch (err) {
      this.holder.initPromise = null;
      throw err;
    }
  }

  /**
   * Runs one SurrealQL statement and returns its rows (first statement's
   * result when the string holds several). DDL returns []. A SELECT ...
   * FROM ONLY result is a single object, wrapped into one row.
   */
  protected async runQuery(
    surql: string,
    bindings: Record<string, unknown> = {},
  ): Promise<Record<string, unknown>[]> {
    await this.ensureReady();
    const start = this.debug ? performance.now() : 0;
    try {
      const collected = (await this.queryable.query(surql, bindings)) as unknown[];
      const first = collected[0];
      if (this.debug) {
        console.log(
          `[yatta-db] ${(performance.now() - start).toFixed(2)}ms  ${surql}`,
          Object.keys(bindings).length ? bindings : "",
        );
      }
      if (first === null || first === undefined) return [];
      if (Array.isArray(first)) return first as Record<string, unknown>[];
      return [first as Record<string, unknown>];
    } catch (err) {
      throw wrapSurrealError(err, surql);
    }
  }

  // ── WHERE translation ──────────────────────────────────────────────────

  /**
   * Translates a WhereClause into a SurrealQL WHERE fragment plus
   * bindings. Mirrors SqlCompiler.compileWhere's validation: an unknown
   * column, an unknown operator, or an unreadable filter is a loud
   * YattaError, never a silent match-everything.
   *
   * The primary-key column is spelled `id` in SurrealQL and compared
   * against a RecordId binding (a plain string never matches a record
   * id). Text matching is case-insensitive, like SQLite's LIKE:
   * the field is lowercased in the query and the pattern in JS.
   */
  protected buildWhere(
    table: string,
    columns: Map<string, ColumnDefinition>,
    where: WhereClause<any> | undefined,
    pkCol: string | null,
    alloc: BindingAllocator,
  ): string {
    if (where !== undefined && where !== null && (typeof where !== "object" || Array.isArray(where))) {
      throw new YattaError(
        `where for "${table}" must be an object filter, got ${Array.isArray(where) ? "an array" : typeof where}. ` +
          `Use { where: { status: "active" } }, or db.${table}.where((f) => f.status.isEqualTo("active")).all().`,
      );
    }
    if (!where || Object.keys(where).length === 0) return "";

    const clauses: string[] = [];
    for (const [key, val] of Object.entries(where)) {
      if (key !== "AND" && key !== "OR" && columns.size > 0 && !columns.has(key)) {
        const known = [...columns.keys()].join(", ");
        throw new YattaError(`Column "${key}" does not exist on table "${table}". Available: ${known}`);
      }
      // The pk column is the record id in SurrealQL.
      const field = key === pkCol ? "id" : key;

      if (key === "AND" || key === "OR") {
        if (!Array.isArray(val)) {
          throw new YattaError(`"${key}" condition must be an array of where clauses`);
        }
        if (val.length === 0) {
          clauses.push(key === "OR" ? "false" : "true");
          continue;
        }
        const nested: string[] = [];
        for (const w of val) {
          const compiled = this.buildWhere(table, columns, w, pkCol, alloc);
          if (compiled !== "") nested.push(compiled);
        }
        if (nested.length === 0) {
          clauses.push(key === "OR" ? "false" : "true");
          continue;
        }
        const joiner = key === "AND" ? " AND " : " OR ";
        clauses.push(nested.length === 1 ? nested[0]! : `(${nested.map((n) => n).join(joiner)})`);
        continue;
      }

      const safeField = qIdent(field);
      const def = columns.get(key);
      // Serializes + validates one filter value (NOT NULL guard, object
      // rejection, JSON stringify, Date handling). The pk column binds
      // as a RecordId instead; a null or wrong-typed pk value is refused
      // here, not by the server.
      const bind = (value: unknown): string => {
        if (key === pkCol) {
          if (value === null || value === undefined) {
            throw new YattaError(
              `Primary key "${key}" on "${table}" cannot be compared to null. Use { ${key}: { isNull: true } } to match missing keys.`,
            );
          }
          const pkDef = columns.get(key);
          if (pkDef?.type === "INTEGER" && (typeof value !== "number" || !Number.isInteger(value))) {
            throw new YattaError(
              `Primary key "${key}" on "${table}" is an integer key, got ${JSON.stringify(value)}.`,
            );
          }
          if (pkDef?.type === "TEXT" && typeof value !== "string") {
            throw new YattaError(
              `Primary key "${key}" on "${table}" is a text key, got ${JSON.stringify(value)}.`,
            );
          }
          try {
            return alloc.alloc(new RecordId(table, value as string | number));
          } catch {
            throw new YattaError(
              `Value ${JSON.stringify(value)} is not a valid record id for "${table}".`,
            );
          }
        }
        return alloc.alloc(this.compiler.serializeValue(table, key, def, value));
      };
      const bindList = (values: unknown[]): string => {
        if (key === pkCol) {
          return alloc.alloc(
            values.map((v) => {
              if (v === null || v === undefined) {
                throw new YattaError(
                  `Primary key "${key}" on "${table}" cannot be compared to null.`,
                );
              }
              try {
                return new RecordId(table, v as string | number);
              } catch {
                throw new YattaError(
                  `Value ${JSON.stringify(v)} is not a valid record id for "${table}".`,
                );
              }
            }),
          );
        }
        return alloc.alloc(values.map((v) => this.compiler.serializeValue(table, key, def, v)));
      };

      if (val === null) {
        clauses.push(`${safeField} IS NONE`);
      } else if (
        typeof val === "object" &&
        !Array.isArray(val) &&
        !(val instanceof Date) &&
        !(val instanceof Uint8Array) &&
        !(val instanceof ArrayBuffer) &&
        !ArrayBuffer.isView(val)
      ) {
        const op = val as Record<string, unknown>;
        for (const opKey of Object.keys(op)) {
          if (!FILTER_OPS.has(opKey)) {
            throw new YattaError(
              `Unknown filter operator "${opKey}" on "${table}.${key}". ` +
                `Supported: ${[...FILTER_OPS].join(", ")}`,
            );
          }
        }

        if (op.eq !== undefined) {
          if (op.eq === null) clauses.push(`${safeField} IS NONE`);
          else clauses.push(`${safeField} = ${bind(op.eq)}`);
        }
        if (op.neq !== undefined) {
          if (op.neq === null) clauses.push(`${safeField} IS NOT NONE`);
          else clauses.push(`${safeField} != ${bind(op.neq)}`);
        }
        if (op.gt !== undefined) clauses.push(`${safeField} > ${bind(op.gt)}`);
        if (op.gte !== undefined) clauses.push(`${safeField} >= ${bind(op.gte)}`);
        if (op.lt !== undefined) clauses.push(`${safeField} < ${bind(op.lt)}`);
        if (op.lte !== undefined) clauses.push(`${safeField} <= ${bind(op.lte)}`);

        // Text matching is case-insensitive (SQLite LIKE is ASCII
        // case-insensitive): lowercase the field in the query, the
        // pattern in JS. A `like` pattern reduces to one of these four
        // shapes or is refused (see translateLike).
        const textOp = (fn: string, text: string): string =>
          `string::${fn}(string::lowercase(${safeField}), ${alloc.alloc(text.toLowerCase())})`;
        if (op.like !== undefined) {
          const translated = translateLike(String(op.like));
          if (translated.kind === "exact") {
            clauses.push(`string::lowercase(${safeField}) = ${alloc.alloc(translated.text.toLowerCase())}`);
          } else if (translated.kind === "contains") {
            clauses.push(textOp("contains", translated.text));
          } else if (translated.kind === "startsWith") {
            clauses.push(textOp("starts_with", translated.text));
          } else {
            clauses.push(textOp("ends_with", translated.text));
          }
        }
        if (op.contains !== undefined) clauses.push(textOp("contains", String(op.contains)));
        if (op.startsWith !== undefined) clauses.push(textOp("starts_with", String(op.startsWith)));
        if (op.endsWith !== undefined) clauses.push(textOp("ends_with", String(op.endsWith)));

        if (op.isNull === true) clauses.push(`${safeField} IS NONE`);
        if (op.isNull === false) clauses.push(`${safeField} IS NOT NONE`);

        if (op.in !== undefined) {
          if (!Array.isArray(op.in)) throw new YattaError(`"in" filter on "${key}" must be an array`);
          if (op.in.length === 0) {
            clauses.push("false");
          } else {
            clauses.push(`${safeField} IN ${bindList(op.in)}`);
          }
        }
        if (op.notIn !== undefined) {
          if (!Array.isArray(op.notIn)) throw new YattaError(`"notIn" filter on "${key}" must be an array`);
          if (op.notIn.length === 0) {
            clauses.push("true");
          } else {
            clauses.push(`${safeField} NOT IN ${bindList(op.notIn)}`);
          }
        }
      } else {
        clauses.push(`${safeField} = ${bind(val)}`);
      }
    }

    return clauses.join(" AND ");
  }

  /** ORDER BY fragment for a find query (pk column spelled `id`). */
  protected buildOrderBy(
    table: string,
    columns: Map<string, ColumnDefinition>,
    orderBy: OrderBy<any> | OrderBy<any>[] | undefined,
    pkCol: string | null,
  ): string {
    if (!orderBy) return "";
    const orders = Array.isArray(orderBy) ? orderBy : [orderBy];
    const parts: string[] = [];
    for (const ord of orders) {
      for (const [column, dir] of Object.entries(ord)) {
        if (columns.size > 0 && !columns.has(column)) {
          throw new YattaError(`Column "${column}" does not exist on table "${table}"`);
        }
        const cleanDir = String(dir).toUpperCase();
        if (cleanDir !== "ASC" && cleanDir !== "DESC") {
          throw new YattaError(`Invalid order direction "${dir}" for column "${column}"`);
        }
        parts.push(`${qIdent(column === pkCol ? "id" : column)} ${cleanDir}`);
      }
    }
    return parts.length > 0 ? `ORDER BY ${parts.join(", ")}` : "";
  }

  /** Decodes one raw SurrealDB record into an ORM row (pk from the record id, values via the dialect). */
  protected decodeRow(
    table: string,
    schema: TableSchema,
    raw: Record<string, unknown>,
  ): Record<string, unknown> {
    void table;
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(raw)) {
      // Search score columns (selected as __yatta_rankN) are not row data.
      if (key.startsWith("__yatta_rank")) continue;
      if (key === "id") {
        // A keyless table has no column to map the record id onto.
        if (pkCol === null) continue;
        out[pkCol] = this.dialect.decodeValue(value, columns.get(pkCol));
        continue;
      }
      out[key] = this.dialect.decodeValue(value, columns.get(key));
    }
    return out;
  }

  /** Validates take/skip the way Table.rowCount does (negative counts are refused, not reinterpreted). */
  protected validateTakeSkip(take: number | undefined, skip: number | undefined): void {
    if (take !== undefined && (!Number.isInteger(take) || take < 0)) {
      throw new YattaError(`take must be a non-negative integer, got ${take}`);
    }
    if (skip !== undefined && (!Number.isInteger(skip) || skip < 0)) {
      throw new YattaError(`skip must be a non-negative integer, got ${skip}`);
    }
  }

  // ── Raw execution ──────────────────────────────────────────────────────

  /**
   * Runs one SurrealQL statement. `params` are positional bindings
   * (`$p0`, `$p1`, … in the statement, in array order); an object
   * passed at runtime is used as named bindings as-is. Returns raw
   * SurrealDB values (RecordId / DateTime objects, not decoded rows) —
   * the session methods decode; this is the escape hatch.
   */
  async run(sql: string, params: unknown[] = [], mode: "get" | "all" | "run" = "all"): Promise<unknown> {
    const bindings: Record<string, unknown> = {};
    if (Array.isArray(params)) {
      params.forEach((v, i) => {
        bindings[`p${i}`] = v;
      });
    } else if (params && typeof params === "object") {
      Object.assign(bindings, params as Record<string, unknown>);
    }
    const rows = await this.runQuery(sql, bindings);
    if (mode === "get") return rows[0] ?? null;
    if (mode === "all") return rows;
    return { lastInsertRowid: 0, changes: rows.length };
  }

  /** Finalizes and purges cached prepared statements. A no-op: this driver keeps none. */
  clearStatementCache(): void {}

  // ── Session CRUD ─────────────────────────────────────────────────────────

  async insert(
    table: string,
    schema: TableSchema,
    row: Record<string, unknown>,
  ): Promise<Record<string, unknown>> {
    await this.ensureReady();
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    const pkDef = pkCol !== null ? columns.get(pkCol) : undefined;
    const alloc = new BindingAllocator();
    const contentParts: string[] = [];

    for (const [key, value] of Object.entries(row)) {
      if (key === pkCol) continue; // the pk is the record id, not a field
      if (!columns.has(key)) {
        throw new YattaError(`Column "${key}" does not exist on table "${table}".`);
      }
      const encoded = this.compiler.serializeValue(table, key, columns.get(key), value);
      contentParts.push(`${qIdent(key)}: ${alloc.alloc(encoded)}`);
    }

    // The record id: supplied, sequenced, generated, or left to the server.
    if (pkCol !== null && row[pkCol] !== undefined) {
      const pkValue = row[pkCol];
      if (pkDef?.type === "INTEGER" && (typeof pkValue !== "number" || !Number.isInteger(pkValue))) {
        throw new YattaError(
          `Cannot insert into "${table}": integer primary key "${pkCol}" needs an integer value, got ${JSON.stringify(pkValue)}.`,
        );
      }
      if (pkDef?.type === "TEXT" && typeof pkValue !== "string") {
        throw new YattaError(
          `Cannot insert into "${table}": text primary key "${pkCol}" needs a string value, got ${JSON.stringify(pkValue)}.`,
        );
      }
      contentParts.push(`${qIdent("id")}: ${alloc.alloc(new RecordId(table, pkValue as string | number))}`);
    } else if (pkCol !== null && pkDef?.autoIncrement) {
      await this.ensureSequence(table);
      contentParts.push(`${qIdent("id")}: sequence::nextval(${surqlStringLiteral(sequenceName(table))})`);
    } else if (pkCol !== null && pkDef?.isUuid) {
      contentParts.push(`${qIdent("id")}: ${alloc.alloc(new RecordId(table, crypto.randomUUID()))}`);
    } else if (pkCol !== null && pkDef?.type === "INTEGER") {
      throw new YattaError(
        `Cannot insert into "${table}": integer primary key "${pkCol}" needs a value. ` +
          `Use col.id() for an auto-incrementing key, or supply the id.`,
      );
    }
    // A TEXT pk with no value, and a keyless table, omit "id": SurrealDB
    // generates a random string record id.

    const created = await this.runQuery(
      `CREATE ${qIdent(table)} CONTENT { ${contentParts.join(", ")} };`,
      alloc.bindings,
    );
    const first = created[0];
    if (!first) {
      throw new YattaError(`Insert into "${table}" returned no row.`);
    }
    return this.decodeRow(table, schema, first);
  }

  async insertMany(
    table: string,
    schema: TableSchema,
    rows: Record<string, unknown>[],
  ): Promise<Record<string, unknown>[]> {
    if (rows.length === 0) return [];
    // One transaction, one insert at a time: the driver is
    // single-connection — never Promise.all per-row work.
    return this.withTxIfNeeded(async (tx) => {
      const out: Record<string, unknown>[] = [];
      for (const row of rows) out.push(await tx.insert(table, schema, row));
      return out;
    });
  }

  async find(
    table: string,
    schema: TableSchema,
    query: CompiledFindQuery,
  ): Promise<Record<string, unknown>[]> {
    await this.ensureReady();
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    this.validateTakeSkip(query.take, query.skip);
    const alloc = new BindingAllocator();
    const whereSql = this.buildWhere(table, columns, query.where, pkCol, alloc);
    const orderSql = this.buildOrderBy(table, columns, query.orderBy, pkCol);
    const selectSql =
      query.select === undefined
        ? "*"
        : query.select
            .map((c) => {
              if (!columns.has(c)) {
                throw new YattaError(`Column "${c}" does not exist on table "${table}".`);
              }
              return qIdent(c === pkCol ? "id" : c);
            })
            .join(", ");
    const limitSql = surrealDialect.compileLimitOffset(query.take, query.skip);
    const surql = [
      `SELECT ${selectSql} FROM ${qIdent(table)}`,
      whereSql ? `WHERE ${whereSql}` : "",
      orderSql,
      limitSql,
    ]
      .filter(Boolean)
      .join(" ")
      .concat(";");
    const rows = await this.runQuery(surql, alloc.bindings);
    return rows.map((r) => this.decodeRow(table, schema, r));
  }

  async count(table: string, schema: TableSchema, where?: WhereClause<any>): Promise<number> {
    await this.ensureReady();
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    const alloc = new BindingAllocator();
    const whereSql = this.buildWhere(table, columns, where, pkCol, alloc);
    const rows = await this.runQuery(
      `SELECT count() FROM ${qIdent(table)}${whereSql ? ` WHERE ${whereSql}` : ""} GROUP ALL;`,
      alloc.bindings,
    );
    const count = (rows[0] as { count?: unknown } | undefined)?.count;
    return typeof count === "number" ? count : 0;
  }

  async update(
    table: string,
    schema: TableSchema,
    where: WhereClause<any>,
    patch: Record<string, unknown>,
  ): Promise<Record<string, unknown>[]> {
    await this.ensureReady();
    if (Object.keys(patch).length === 0) return [];
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    if (pkCol !== null && pkCol in patch) {
      throw new YattaError(
        `Cannot update the primary key column "${pkCol}" on "${table}": a SurrealDB record id is immutable. ` +
          `Delete the record and create a new one instead.`,
      );
    }
    const alloc = new BindingAllocator();
    const setParts: string[] = [];
    for (const [key, value] of Object.entries(patch)) {
      if (!columns.has(key)) {
        throw new YattaError(`Column "${key}" does not exist on table "${table}".`);
      }
      const encoded = this.compiler.serializeValue(table, key, columns.get(key), value);
      setParts.push(`${qIdent(key)} = ${alloc.alloc(encoded)}`);
    }
    const whereSql = this.buildWhere(table, columns, where, pkCol, alloc);
    // UPDATE returns the updated records (no RETURNING clause in SurrealQL).
    const rows = await this.runQuery(
      `UPDATE ${qIdent(table)} SET ${setParts.join(", ")}${whereSql ? ` WHERE ${whereSql}` : ""};`,
      alloc.bindings,
    );
    return rows.map((r) => this.decodeRow(table, schema, r));
  }

  async delete(table: string, schema: TableSchema, where: WhereClause<any>): Promise<number> {
    await this.ensureReady();
    // DELETE returns no rows, so the count is taken first and the same
    // filter deletes exactly those rows.
    const before = await this.count(table, schema, where);
    if (before === 0) return 0;
    const columns = columnsOf(schema);
    const pkCol = pkColumnName(schema);
    const alloc = new BindingAllocator();
    const whereSql = this.buildWhere(table, columns, where, pkCol, alloc);
    await this.runQuery(
      `DELETE FROM ${qIdent(table)}${whereSql ? ` WHERE ${whereSql}` : ""};`,
      alloc.bindings,
    );
    return before;
  }

  async upsert(
    table: string,
    schema: TableSchema,
    plan: CompiledUpsertPlan,
  ): Promise<Record<string, unknown>> {
    // No atomic upsert through the compiler: the transactional
    // find-first-then-update/insert fallback, the same behaviour as
    // SQLite. Runs on this session when already inside a transaction
    // (nesting is unsupported), otherwise opens one.
    return this.withTxIfNeeded(async (tx) => {
      const existing = await tx.find(table, schema, { where: plan.where, take: 1 });
      if (existing.length > 0) {
        if (Object.keys(plan.updateRow).length === 0) return existing[0]!;
        const pkCol = pkColumnName(schema) ?? "id";
        const pk = (existing[0] as Record<string, unknown>)[pkCol];
        const updated = await tx.update(table, schema, { [pkCol]: pk } as WhereClause<any>, plan.updateRow);
        return updated[0] ?? existing[0]!;
      }
      return tx.insert(table, schema, plan.createRow);
    });
  }

  // ── Full-text search ─────────────────────────────────────────────────────

  /**
   * Full-text search over the table's searchable columns, ranked by BM25.
   * `rank` is `-search::score`, keeping the contract's convention
   * (smaller = more relevant). Groups are ANDed, alternatives inside a
   * group are ORed; one `search::score(n)` per group. A single group
   * pages in SQL; several groups are sorted by total score in JS (the
   * ORDER BY spelling cannot sum score aliases) and then sliced.
   */
  async search(
    table: string,
    schema: TableSchema,
    query: CompiledSearchQuery,
  ): Promise<Array<{ row: Record<string, unknown>; rank: number }>> {
    const cols = searchableColumns(schema);
    if (cols.length === 0) {
      throw new YattaError(
        `Table "${table}" has no searchable columns. ` +
          `Mark a text column with .searchable() to make the table searchable.`,
      );
    }
    const pkCol = pkColumnName(schema);
    if (pkCol === null) {
      throw new YattaError(
        `Table "${table}" has no primary key column, so search cannot map index entries back to rows. ` +
          `Add col.id() or col.uuid() to search it.`,
      );
    }

    const restricted = query.columns.length > 0 ? query.columns : null;
    if (restricted) {
      for (const c of restricted) {
        if (!cols.includes(c)) {
          throw new YattaError(
            `Column "${c}" on table "${table}" is not searchable. ` +
              `Searchable columns: ${cols.join(", ")}. ` +
              `Non-searchable columns are never searched, and naming one here is refused rather than silently ignored.`,
          );
        }
        qIdent(c);
      }
    }

    if (query.expandedGroups.length === 0) return [];

    // Creates (or repairs) the index on first use, so a table opened
    // without a schema sync still searches correctly.
    await this.ensureSearchIndex(table, schema);

    const columns = columnsOf(schema);
    const targetCols = restricted ?? cols;
    const predicates: string[] = [];
    const scoreCols: string[] = [];
    query.expandedGroups.forEach((group, gi) => {
      const alternatives: string[] = [];
      for (const phrase of group) {
        if (phrase.length === 0) continue;
        const text = phrase.join(" ");
        for (const c of targetCols) {
          alternatives.push(`${qIdent(c)} @${gi}@ ${surqlStringLiteral(text)}`);
        }
      }
      if (alternatives.length === 0) return;
      predicates.push(alternatives.length > 1 ? `(${alternatives.join(" OR ")})` : alternatives[0]!);
      scoreCols.push(`search::score(${gi}) AS __yatta_rank${gi}`);
    });
    if (predicates.length === 0) return [];

    const alloc = new BindingAllocator();
    const extraWhere = this.buildWhere(table, columns, query.where, pkCol, alloc);
    const whereSql = [...predicates, ...(extraWhere ? [extraWhere] : [])].join(" AND ");

    // One group: SQL orders by its score and pages. Several groups: the
    // total score is a JS sum, so all matches are fetched, sorted, sliced.
    const singleGroup = predicates.length === 1;
    this.validateTakeSkip(query.limit, query.offset);
    const orderSql = singleGroup ? "ORDER BY __yatta_rank0 DESC" : "";
    const limitSql =
      singleGroup && query.limit !== undefined ? `LIMIT ${query.limit}` : "";
    const startSql =
      singleGroup && query.offset !== undefined ? `START ${query.offset}` : "";
    const rows = await this.runQuery(
      [
        `SELECT *, ${scoreCols.join(", ")} FROM ${qIdent(table)}`,
        `WHERE ${whereSql}`,
        orderSql,
        limitSql,
        startSql,
      ]
        .filter(Boolean)
        .join(" ")
        .concat(";"),
      alloc.bindings,
    );

    const scored = rows.map((r) => {
      let total = 0;
      for (let gi = 0; gi < predicates.length; gi++) {
        const s = (r as Record<string, unknown>)[`__yatta_rank${gi}`];
        if (typeof s === "number") total += s;
      }
      return { row: this.decodeRow(table, schema, r), rank: -total };
    });
    scored.sort((a, b) => a.rank - b.rank);
    if (singleGroup) return scored;
    const offset = query.offset ?? 0;
    return query.limit === undefined ? scored.slice(offset) : scored.slice(offset, offset + query.limit);
  }

  /**
   * Maintains one row's full-text index entry. A no-op: SurrealDB's
   * full-text index maintains itself on every write, so there is no
   * separate index entry to insert, replace, or delete.
   */
  async syncSearchRow(
    _table: string,
    _schema: TableSchema,
    _row: Record<string, unknown>,
    _op: "insert" | "update" | "delete",
  ): Promise<void> {}

  /** Rebuilds one table's full-text indexes from its current rows (REBUILD INDEX per searchable column). */
  async rebuildSearchIndex(table: string, schema: TableSchema): Promise<void> {
    const cols = searchableColumns(schema);
    if (cols.length === 0) {
      throw new YattaError(
        `Table "${table}" has no searchable columns, so there is no search index to rebuild. ` +
          `Mark a text column with .searchable() first.`,
      );
    }
    await this.ensureReady();
    const info = await this.tableInfo(table);
    if (Object.keys(info.fields).length === 0) {
      throw new YattaError(`Table "${table}" does not exist in this database, so its search index cannot be rebuilt.`);
    }
    if (pkColumnName(schema) === null) {
      throw new YattaError(
        `Table "${table}" has no primary key column, so its search index cannot be rebuilt. ` +
          `Add col.id() or col.uuid() to search it.`,
      );
    }
    await this.ensureSearchIndex(table, schema);
    for (const c of cols) {
      await this.runQuery(`REBUILD INDEX ${qIdent(ftsIndexName(table, c))} ON TABLE ${qIdent(table)};`);
    }
  }

  /**
   * The indexed vocabulary for a table: every distinct term in its
   * searchable values, tokenized the same way the core tokenizes query
   * text. SurrealDB exposes no vocabulary table, so this scans the base
   * table (the same fallback the SQLite adapter uses when its vocab
   * table is absent).
   */
  async searchVocabulary(table: string, schema: TableSchema): Promise<Set<string>> {
    const cols = searchableColumns(schema);
    const terms = new Set<string>();
    if (cols.length === 0) return terms;
    await this.ensureReady();
    const rows = await this.runQuery(
      `SELECT ${cols.map((c) => qIdent(c)).join(", ")} FROM ${qIdent(table)};`,
    );
    for (const row of rows) {
      for (const c of cols) {
        const value = row[c];
        if (typeof value === "string") {
          for (const token of tokenizeText(value)) terms.add(token);
        }
      }
    }
    return terms;
  }

  /**
   * No standalone FTS table exists on this driver: the BM25 indexes live
   * on the table itself and the engine removes deleted rows from them,
   * so there is nothing for Table.delete to clean up. Always false.
   */
  async ftsTableExists(_table: string): Promise<boolean> {
    return false;
  }

  /**
   * Makes sure one table's full-text index exists: the shared analyzer
   * plus one FULLTEXT index per searchable column. Called by `search()`
   * so a first search never fails on a missing index, and by
   * `syncSchema` so a fresh database is indexed up front.
   */
  async ensureSearchIndex(table: string, schema: TableSchema): Promise<void> {
    const cols = searchableColumns(schema);
    if (cols.length === 0) return;
    await this.ensureReady();
    const info = await this.tableInfo(table);
    if (Object.keys(info.fields).length === 0) {
      throw new YattaError(
        `Table "${table}" does not exist in this database, so it cannot be searched. ` +
          `Create it first (a schema with autoMigrate creates tables on open).`,
      );
    }
    if (pkColumnName(schema) === null) {
      throw new YattaError(
        `Table "${table}" has no primary key column, so search cannot map index entries back to rows. ` +
          `Add col.id() or col.uuid() to search it.`,
      );
    }
    await this.runQuery(
      `DEFINE ANALYZER IF NOT EXISTS ${qIdent(FTS_ANALYZER)} TOKENIZERS class FILTERS lowercase, ascii;`,
    );
    for (const c of cols) {
      await this.runQuery(
        `DEFINE INDEX IF NOT EXISTS ${qIdent(ftsIndexName(table, c))} ON TABLE ${qIdent(table)} ` +
          `FIELDS ${qIdent(c)} FULLTEXT ANALYZER ${qIdent(FTS_ANALYZER)} BM25 HIGHLIGHTS;`,
      );
    }
  }

  /** `INFO FOR TABLE` result for one table. A missing table returns empty fields/indexes, not an error. */
  protected async tableInfo(table: string): Promise<{
    fields: Record<string, string>;
    indexes: Record<string, string>;
  }> {
    const rows = await this.runQuery(`INFO FOR TABLE ${qIdent(table)};`);
    const info = rows[0] as
      | { fields?: Record<string, string>; indexes?: Record<string, string> }
      | undefined;
    return { fields: info?.fields ?? {}, indexes: info?.indexes ?? {} };
  }

  /** Creates a table's auto-increment sequence when it is not known to exist yet (safety net for inserts without syncSchema). */
  protected async ensureSequence(table: string): Promise<void> {
    if (this.holder.ensuredSequences.has(table)) return;
    await this.runQuery(
      `DEFINE SEQUENCE IF NOT EXISTS ${qIdent(sequenceName(table))} START 1;`,
    );
    this.holder.ensuredSequences.add(table);
  }

  /** Runs fn on this session when already inside a transaction, otherwise inside a fresh one. */
  protected async withTxIfNeeded<R>(fn: (tx: DatabaseSession<"async">) => Promise<R>): Promise<R> {
    if (this.inTransaction) return fn(this);
    return this.transaction(fn);
  }

  /**
   * Creates the migration-marker table (`_yatta_migrations`) with
   * DEFINE TABLE / DEFINE FIELD. Runs on this session, so it works on
   * a transaction child session as well as the root adapter. The `id`
   * is the server-generated record id, not a field, so it is not
   * defined (like syncSchema skips non-`id` pk columns).
   */
  async ensureMigrationTable(): Promise<void> {
    await this.ensureReady();
    await this.runQuery(`DEFINE TABLE IF NOT EXISTS _yatta_migrations SCHEMAFULL TYPE NORMAL;`);
    await this.runQuery(`DEFINE FIELD IF NOT EXISTS name ON TABLE _yatta_migrations TYPE string;`);
    await this.runQuery(`DEFINE FIELD IF NOT EXISTS hash ON TABLE _yatta_migrations TYPE option<string>;`);
    await this.runQuery(`DEFINE FIELD IF NOT EXISTS applied_at ON TABLE _yatta_migrations TYPE option<datetime>;`);
    await this.runQuery(
      `DEFINE INDEX IF NOT EXISTS uniq__yatta_migrations_name ON TABLE _yatta_migrations FIELDS name UNIQUE;`,
    );
  }

  /** Names of migrations already recorded as applied. */
  async listAppliedMigrations(): Promise<string[]> {
    const rows = await this.runQuery(`SELECT name FROM _yatta_migrations;`);
    return rows.map((r) => r.name as string);
  }

  /**
   * Records one migration as applied (ignored when already present —
   * the check-then-create runs under the migration lock, so no race).
   */
  async recordMigration(name: string): Promise<void> {
    const applied = await this.listAppliedMigrations();
    if (applied.includes(name)) return;
    await this.runQuery(
      `INSERT INTO _yatta_migrations (name, hash, applied_at) VALUES ($name, $hash, time::now());`,
      { name, hash: "migration" },
    );
  }

  // ── Raw SurrealQL ──────────────────────────────────────────────────────

  /**
   * Raw SurrealQL escape hatch. Reads (SELECT / INFO / RETURN, or
   * anything with a RETURNING clause) return their rows; writes return
   * their change count — the number of records the statement returned
   * (CREATE / UPDATE / UPSERT return their records; DEFINE / REMOVE
   * return none, so they report 0; DELETE returns none either, so a raw
   * DELETE reports 0 affected rows — use session.delete() for a count).
   * Positional params bind as `$p0`, `$p1`, … in array order.
   */
  async executeRaw(sql: string, params: unknown[] = []): Promise<QueryResult> {
    const head = sql.trimStart().toUpperCase();
    const isRead =
      head.startsWith("SELECT") ||
      head.startsWith("INFO") ||
      head.startsWith("RETURN") ||
      /RETURNING\b/i.test(sql);
    const rows = (await this.run(sql, params, "all")) as Record<string, unknown>[];
    if (isRead) return { rows, affectedRows: rows.length };
    return { rows: [], affectedRows: rows.length };
  }

  /** Runs multi-statement SurrealQL (DDL scripts, migrations). */
  async executeBatch(sql: string): Promise<void> {
    await this.ensureReady();
    try {
      await this.queryable.query(sql);
    } catch (err) {
      throw wrapSurrealError(err, sql);
    }
  }

  // ── Transactions ─────────────────────────────────────────────────────────

  /**
   * Runs `fn` inside a SurrealDB transaction (beginTransaction() +
   * commit()/cancel()). `fn` receives a child session bound to the
   * transaction — using the root session inside `fn` would write
   * outside it. A nested transaction() throws: SurrealDB has no nested
   * transactions and no savepoints. TransactionOptions are accepted and
   * ignored: SurrealDB exposes no immediate/deferred mode or
   * isolation-level choice on this API.
   */
  async transaction<R>(
    fn: (txSession: DatabaseSession<"async">) => Promise<R>,
    _options?: TransactionOptions,
  ): Promise<R> {
    await this.ensureReady();
    if (this.inTransaction) {
      throw new YattaError(
        "SurrealDB does not support nested transactions: there is no SAVEPOINT spelling and " +
          "SurrealTransaction has no beginTransaction(). Restructure the work into one transaction, " +
          "or run the inner part on the transaction session you already hold.",
      );
    }
    let tx: SurrealTransaction;
    try {
      tx = await this.requireDb().beginTransaction();
    } catch (err) {
      throw wrapSurrealError(err);
    }
    this.holder.activeTx++;
    const txSession = new SurrealDBSession(this.holder, tx, true, this.debug);
    try {
      const result = await fn(txSession);
      try {
        await tx.commit();
      } catch (err) {
        throw wrapSurrealError(err);
      }
      return result;
    } catch (err) {
      try {
        await tx.cancel();
      } catch {
        // The transaction is already gone (commit failed, server dropped
        // it): the original error is the one that matters.
      }
      throw err;
    } finally {
      this.holder.activeTx--;
    }
  }
}

/**
 * The SurrealDB adapter: the root session plus the connection-level
 * operations (schema sync, migration lock, backup/restore, close). The
 * root adapter IS the root session.
 */
export class SurrealDBAdapter extends SurrealDBSession implements DatabaseAdapter<"async"> {
  readonly driver = "surrealdb" as const;
  /** Resolved endpoint URL (`"mem://"` by default). */
  readonly path: string;

  constructor(options: SurrealDBAdapterOptions = {}) {
    const url = options.url ?? "mem://";
    const namespace = options.namespace ?? "yatta";
    const database = options.database ?? "yatta";
    // The Surreal client is NOT created here: its engines need
    // @surrealdb/node, which only loads through a dynamic import (see
    // loadSurrealNode), so the client is created lazily in ensureReady().
    // Remote (ws/wss) engines are registered alongside the embedded Node
    // engines there, so one client serves both endpoints.
    // createNodeEngines registers mem/rocksdb/surrealkv;
    // createRemoteEngines registers ws/wss/http.
    const holder: SurrealHolder = {
      db: null,
      url,
      namespace,
      database,
      initPromise: null,
      initialized: false,
      closed: false,
      schemas: new Map(),
      activeTx: 0,
      ensuredSequences: new Set(),
    };
    super(holder, null, false, options.debug ?? false);
    this.path = url;
  }

  /** Eagerly wait for initialization (connect + namespace/database selection). */
  async ready(): Promise<void> {
    await this.ensureReady();
  }

  /**
   * Applies a declarative schema: creates missing tables and fields
   * (DEFINE TABLE / DEFINE FIELD ... IF NOT EXISTS), sequences for
   * auto-increment keys, plain/unique indexes, and the full-text
   * indexes for searchable columns. Idempotent: re-running it is a
   * no-op. References are not enforced (no foreign keys) and enum
   * values are enforced with ASSERT, not CHECK.
   */
  async syncSchema(schema: DatabaseSchema): Promise<void> {
    await this.ensureReady();
    await this.ensureMigrationTable();
    for (const [tableName, tableDef] of Object.entries(schema)) {
      qIdent(tableName);
      const pkCol = pkColumnName(tableDef);
      const indexedCols = new Set<string>();

      // One timestamp orders a table's rows. Two marked columns would
      // leave rollups guessing which one is the time axis, so the
      // schema is rejected before any DDL for the table runs.
      const timeSeriesCols = Object.entries(tableDef)
        .filter(([, b]) => b.def.isTimeSeries)
        .map(([name]) => name);
      if (timeSeriesCols.length > 1) {
        throw new YattaError(
          `Table "${tableName}" marks more than one time-series column (${timeSeriesCols.join(", ")}). ` +
            `Mark exactly one timestamp column per table with .timeSeries().`,
        );
      }

      await this.runQuery(`DEFINE TABLE IF NOT EXISTS ${qIdent(tableName)} SCHEMAFULL TYPE NORMAL;`);

      if (Object.values(tableDef).some((b) => b.def.autoIncrement)) {
        await this.ensureSequence(tableName);
      }

      for (const [colName, colBuilder] of Object.entries(tableDef)) {
        const def = colBuilder.def;
        // A pk column named anything other than `id` IS the record id:
        // defining a field for it would create a second, required field
        // the adapter never writes. `id` itself is definable (it types
        // the record id) and is listed by INFO FOR TABLE.
        if (colName === pkCol && colName !== "id") continue;

        const baseType = surrealDialect.mapColumnType(def);
        const nullable = !def.notNull && !def.primaryKey;
        const typeSql = nullable ? `option<${baseType}>` : baseType;
        let fieldSql =
          `DEFINE FIELD IF NOT EXISTS ${qIdent(colName)} ON TABLE ${qIdent(tableName)} ` +
          `TYPE ${typeSql}`;
        if (def.defaultValue !== undefined) {
          fieldSql += ` DEFAULT ${surrealDialect.compileColumnDefault(def)}`;
        }
        if (def.checkValues?.length) {
          const values = def.checkValues.map((v) => surqlStringLiteral(v)).join(", ");
          fieldSql += ` ASSERT $value IN [${values}]`;
        }
        await this.runQuery(`${fieldSql};`);

        if (def.unique) {
          await this.runQuery(
            `DEFINE INDEX IF NOT EXISTS ${qIdent(`uniq_${tableName}_${colName}`)} ` +
              `ON TABLE ${qIdent(tableName)} FIELDS ${qIdent(colName)} UNIQUE;`,
          );
          indexedCols.add(colName);
        } else if ((def.isIndex || def.references) && !indexedCols.has(colName)) {
          indexedCols.add(colName);
          await this.runQuery(
            `DEFINE INDEX IF NOT EXISTS ${qIdent(`idx_${tableName}_${colName}`)} ` +
              `ON TABLE ${qIdent(tableName)} FIELDS ${qIdent(colName)};`,
          );
        }
        if (def.isTimeSeries && !def.isIndex && !indexedCols.has(colName)) {
          indexedCols.add(colName);
          await this.runQuery(
            `DEFINE INDEX IF NOT EXISTS ${qIdent(`idx_timeseries_${tableName}_${colName}`)} ` +
              `ON TABLE ${qIdent(tableName)} FIELDS ${qIdent(colName)};`,
          );
        }
      }

      this.holder.schemas.set(tableName, tableDef);
      await this.ensureSearchIndex(tableName, tableDef);
    }
  }

  /** User tables (this adapter creates no internal tables). */
  async listTables(): Promise<string[]> {
    await this.ensureReady();
    const rows = await this.runQuery("INFO FOR DB;");
    const info = rows[0] as { tables?: Record<string, string> } | undefined;
    // The migration-marker table is infrastructure, not a user table —
    // the other adapters exclude it from listTables() the same way.
    return Object.keys(info?.tables ?? {}).filter((t) => t !== "_yatta_migrations").sort();
  }

  async listColumns(table: string): Promise<IntrospectedColumn[]> {
    await this.ensureReady();
    // A table with only a non-"id" pk column defines no fields at all,
    // so field-emptiness cannot prove absence: membership in INFO FOR
    // DB is the existence test.
    if (!(await this.listTables()).includes(table)) return [];
    const info = await this.tableInfo(table);
    const recorded = this.holder.schemas.get(table);
    const recordedCols = recorded ? columnsOf(recorded) : new Map<string, ColumnDefinition>();
    const pkCol = recorded ? pkColumnName(recorded) : null;

    const out: IntrospectedColumn[] = [];
    const seen = new Set<string>();
    for (const [name, defineSql] of Object.entries(info.fields)) {
      // "DEFINE FIELD n ON widget TYPE int PERMISSIONS FULL" — the type
      // is everything between "TYPE " and the next clause keyword
      // (PERMISSIONS / DEFAULT / ASSERT) or the end.
      const match = /TYPE\s+(.+?)(?:\s+(?:PERMISSIONS|DEFAULT|ASSERT)\b|$)/.exec(defineSql);
      const rawType = (match?.[1] ?? "any").trim();
      const nullable = rawType.startsWith("none |") || rawType.startsWith("option<");
      const type = rawType
        .replace(/^none \|\s*/, "")
        .replace(/^option<(.+)>$/, "$1")
        .trim();
      const def = recordedCols.get(name);
      out.push({
        name,
        type,
        nullable: nullable || (def !== undefined && def.notNull === false),
        primaryKey: pkCol !== null && name === pkCol,
      });
      seen.add(name);
    }

    // A pk column named anything other than `id` has no DEFINE FIELD
    // (it is the record id), so it is synthesized from the recorded
    // schema, first — the way SQLite lists the pk first.
    if (pkCol !== null && pkCol !== "id" && !seen.has(pkCol)) {
      const def = recordedCols.get(pkCol);
      if (def) {
        out.unshift({
          name: pkCol,
          type: surrealDialect.mapColumnType(def),
          nullable: false,
          primaryKey: true,
        });
      }
    }
    return out;
  }

  /**
   * Exclusive lock across migrations. SurrealDB has no advisory lock,
   * so the lock is a transaction: migrations run atomically, and on
   * the embedded single-process engine nothing else can interleave.
   * Against a remote server this is atomicity, not cross-process
   * exclusion — two processes migrating the same remote database at
   * once are not serialized. If already inside a transaction, fn runs
   * in it.
   */
  async withMigrationLock<R>(
    fn: (session: DatabaseSession<"async">) => Promise<R>,
  ): Promise<R> {
    return this.withTxIfNeeded(fn);
  }

  /**
   * Backs up the database as SurrealQL text (db.export(): DEFINEs plus
   * INSERTs) written to `destPath`, creating the parent directory.
   */
  async backup(destPath: string): Promise<void> {
    await this.ensureReady();
    let exported: unknown;
    try {
      exported = await this.requireDb().export();
    } catch (err) {
      throw wrapSurrealError(err);
    }
    if (typeof exported !== "string") {
      throw new YattaError(
        `SurrealDB backup failed: export() returned ${typeof exported}, not SurrealQL text.`,
      );
    }
    try {
      const parentDir = path.dirname(destPath);
      if (parentDir && parentDir !== "." && !fs.existsSync(parentDir)) {
        fs.mkdirSync(parentDir, { recursive: true });
      }
      fs.writeFileSync(destPath, exported, "utf8");
    } catch (err: any) {
      throw new YattaError(`Backup failed: ${err?.message ?? String(err)}`);
    }
  }

  /**
   * Restores the database from a backup file: removes every user table,
   * then imports the file's SurrealQL. A replay, not a file swap (see
   * the header): sequences keep their current value and statements the
   * import cannot apply fail on their own without stopping the rest.
   * Refused inside a transaction.
   */
  async restore(sourcePath: string): Promise<void> {
    if (!fs.existsSync(sourcePath)) {
      throw new YattaError(`Backup file not found: ${sourcePath}`);
    }
    await this.ensureReady();
    if (this.inTransaction) {
      throw new YattaError("Cannot restore inside a transaction.");
    }
    let content: string;
    try {
      content = fs.readFileSync(sourcePath, "utf8");
    } catch (err: any) {
      throw new YattaError(`Cannot read backup file: ${err?.message ?? String(err)}`);
    }
    if (content.trim() === "") {
      throw new YattaError("Backup file is empty — it holds no schema.");
    }
    for (const table of await this.listTables()) {
      await this.runQuery(`REMOVE TABLE ${qIdent(table)};`);
    }
    this.holder.ensuredSequences.clear();
    try {
      await this.requireDb().import(content);
    } catch (err) {
      throw wrapSurrealError(err);
    }
  }

  /** Closes the SurrealDB connection. Idempotent. A never-connected adapter has no client to close. */
  async close(): Promise<void> {
    if (this.holder.closed) return;
    this.holder.closed = true;
    try {
      await this.holder.db?.close();
    } catch (err) {
      throw wrapSurrealError(err);
    }
  }
}
