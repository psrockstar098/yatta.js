// PostgresDialect: the Postgres (PGlite) implementation of SqlDialect.
//
// Phase 2 of the multi-database ORM refactor. Same questions as
// SqliteDialect, different answers: $n placeholders, BIGINT for
// col.integer() (epoch-ms timestamps overflow INTEGER), IDENTITY for
// col.id(), BOOLEAN/JSONB as real types, ILIKE for LIKE (Postgres LIKE
// is case-sensitive; SQLite's is ASCII case-insensitive), explicit NULLS
// FIRST/LAST to match SQLite's default ordering, LIMIT ALL for an
// unbounded read, and a to_char CURRENT_TIMESTAMP default that emits
// exactly the toISOString() format.
//
// Rebases of the Gemini design (f5), which was written against the
// pre-split code and PGlite 0.3.7:
//   - f5's compileColumnDefault returned `string | null` and rendered
//     CURRENT_TIMESTAMP as `to_char(timezone('UTC', now()),
//     'YYYY-MM-DD HH24:MI:SS')` — no `T`, no millis, no `Z`. The real
//     interface returns `string`, and the probe-verified format is
//     `to_char(now() AT TIME ZONE 'UTC',
//     'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`, which renders exactly
//     `2026-11-24T15:06:41.248Z` (see
//     ~/workspace/scratch/pglite-probe-results.md).
//   - f5's quoteIdent threw on non-plain identifiers. The real
//     SqliteDialect doubles embedded quotes instead; this mirrors it, so
//     a schema name with odd characters is escaped, not rejected.
//   - f5's compileLikePredicate took two arguments and always emitted
//     ESCAPE. The real interface takes an `escape` flag: op.like gets a
//     bare ILIKE, contains/startsWith/endsWith get `ILIKE … ESCAPE '\'`.
//   - f5's compileOrderNulls returned the full "ASC NULLS FIRST" string.
//     The real interface returns only the suffix after ASC/DESC.
//   - f5's compileCreateTableStatements returned `string[]` and built
//     the CREATE TABLE inline. The real interface returns
//     `[string, ...string[]]` and has the granular fragment methods,
//     which this implements (mirroring SqliteDialect's structure and
//     index rules) plus the tsvector generated column + GIN index.
//   - f5's decodeValue did not handle INT8 (BigInt) or TIMESTAMPTZ
//     (Date). PGlite 0.6.0 returns INT8 as number-when-safe /
//     BigInt-when-unsafe and TIMESTAMPTZ as a JS Date; both are handled
//     here (BigInt converts to Number when safe, throws when not).
//   - f5 used an expression GIN index for search. The prose §3.5 design
//     specifies a GENERATED tsvector column + GIN index, which the probe
//     verified; this implements that (column `__yatta_tsv`).
//   - compileUpsert returns null, like SQLite: the core uses the
//     transactional find-first-then-update/insert fallback. An atomic
//     ON CONFLICT path is a later optimisation, not a behaviour change.

import { YattaError } from "../errors";
import type { ColumnDefinition, TableSchema } from "../schema";
import type { CompiledSql, SqlDialect, UpsertPlan } from "../sql_dialect";

const ALLOWED_TYPES = ["INTEGER", "TEXT", "REAL", "BLOB"];
const ALLOWED_ON_DELETE = ["CASCADE", "SET NULL", "RESTRICT"];

/** Name of the generated tsvector column holding a table's search vector. Reserved: never a schema column. */
export const PGLITE_SEARCH_VECTOR_COLUMN = "__yatta_tsv";

/**
 * The tsvector expression for a table's searchable columns, used both by
 * the generated column and by the search query. One helper builds both,
 * so the GIN index always matches the expression the search runs.
 */
export function searchVectorExpression(searchableCols: string[]): string {
  // ::text keeps a searchable non-text column working (coalesce needs
  // matching types); a text column casts to itself.
  const parts = searchableCols.map((c) => `coalesce("${c.replace(/"/g, '""')}"::text, '')`);
  return `to_tsvector('simple', ${parts.join(" || ' ' || ")})`;
}

export class PostgresDialect implements SqlDialect {
  readonly name = "pglite";
  readonly supportsReturning = true;
  readonly likeCaseInsensitiveByDefault = false;

  quoteIdent(ident: string): string {
    return `"${ident.replace(/"/g, '""')}"`;
  }

  placeholder(index1Based: number): string {
    return `$${index1Based}`;
  }

  mapColumnType(def: ColumnDefinition): string {
    if (def.autoIncrement) return "INTEGER GENERATED BY DEFAULT AS IDENTITY";
    if (def.isBoolean) return "BOOLEAN";
    if (def.isJson) return "JSONB";
    if (!ALLOWED_TYPES.includes(def.type)) {
      throw new YattaError(
        `Invalid column type "${def.type}". Expected one of ${ALLOWED_TYPES.join(", ")}.`,
      );
    }
    switch (def.type) {
      case "INTEGER":
        // BIGINT is mandatory: epoch-ms timestamps overflow INTEGER.
        return "BIGINT";
      case "REAL":
        return "DOUBLE PRECISION";
      case "BLOB":
        return "BYTEA";
      case "TEXT":
      default:
        // Covers col.text(), col.uuid(), col.date(), col.enum().
        return "TEXT";
    }
  }

  compileColumnDefault(def: ColumnDefinition): string {
    if (def.defaultValue === undefined) return "";
    if (def.defaultValue === null) return "NULL";

    if (def.defaultValue === "CURRENT_TIMESTAMP") {
      /*
       * Exactly the toISOString() format, for the same reason as the
       * SQLite strftime expression: every other write path puts
       * `Date#toISOString()` in the same column, and the filter DSL
       * compares TEXT lexicographically. A bare `now()` (TIMESTAMPTZ)
       * would render "2026-11-24 15:06:41.248+00" — a space, no `T`,
       * no `Z` — and sort before every ISO row from the same day.
       * Verified live against PGlite 0.6.0:
       * `2026-11-24T15:06:41.248Z`.
       */
      return `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;
    }
    if (typeof def.defaultValue === "number" || def.isBoolean) {
      return String(def.isBoolean ? (def.defaultValue ? "TRUE" : "FALSE") : def.defaultValue);
    }
    if (def.isJson) {
      const jsonStr =
        typeof def.defaultValue === "string"
          ? def.defaultValue
          : JSON.stringify(def.defaultValue);
      return `'${jsonStr.replace(/'/g, "''")}'::jsonb`;
    }
    // A structured default must be serialized, not coerced (see
    // SqliteDialect.compileColumnDefault for why).
    if (typeof def.defaultValue === "object") {
      return `'${JSON.stringify(def.defaultValue).replace(/'/g, "''")}'`;
    }

    return `'${String(def.defaultValue).replace(/'/g, "''")}'`;
  }

  compileColumnFragment(colName: string, def: ColumnDefinition, mode: "create" | "alter"): string {
    const safeName = colName.replace(/"/g, '""');
    if (def.references?.onDelete && !ALLOWED_ON_DELETE.includes(def.references.onDelete)) {
      throw new YattaError(`Invalid ON DELETE action "${def.references.onDelete}" for "${colName}". Expected one of ${ALLOWED_ON_DELETE.join(", ")}.`);
    }
    // IDENTITY carries the auto-increment; the type mapping above throws
    // for an unknown base type.
    let s = `"${safeName}" ${this.mapColumnType(def)}`;

    if (mode === "create") {
      if (def.primaryKey) s += " PRIMARY KEY";
    } else if (def.primaryKey) {
      throw new YattaError(`Cannot add PRIMARY KEY column "${colName}" via ALTER TABLE in Postgres.`);
    }

    if (def.notNull) {
      if (mode === "alter" && def.defaultValue === undefined) {
        throw new YattaError(
          `Cannot add NOT NULL column "${colName}" without a default value in Postgres. ` +
            `Add .default(...) or make it .nullable().`,
        );
      }
      s += " NOT NULL";
    }

    if (mode === "create" && def.unique) s += " UNIQUE";
    if (def.defaultValue !== undefined) s += ` DEFAULT ${this.compileColumnDefault(def)}`;
    if (def.references) {
      s += ` REFERENCES "${def.references.table.replace(/"/g, '""')}"("${def.references.column.replace(/"/g, '""')}")`;
      if (def.references.onDelete) s += ` ON DELETE ${def.references.onDelete}`;
    }
    if (def.checkValues?.length) {
      s += ` CHECK("${safeName}" IN (${def.checkValues.map((v) => `'${v.replace(/'/g, "''")}'`).join(", ")}))`;
    }

    return s;
  }

  compileCreateTableSql(table: string, columnFragments: string[]): string {
    return `CREATE TABLE IF NOT EXISTS "${table.replace(/"/g, '""')}" (${columnFragments.join(", ")});`;
  }

  compileAddColumnSql(table: string, fragment: string): string {
    return `ALTER TABLE "${table.replace(/"/g, '""')}" ADD COLUMN ${fragment};`;
  }

  compileIndexSql(table: string, colName: string, kind: "plain" | "timeseries" | "unique"): string {
    const t = table.replace(/"/g, '""');
    const c = colName.replace(/"/g, '""');
    if (kind === "unique") {
      const uniqName = `uniq_${table}_${colName}`.replace(/"/g, '""');
      return `CREATE UNIQUE INDEX IF NOT EXISTS "${uniqName}" ON "${t}" ("${c}");`;
    }
    if (kind === "timeseries") {
      const tsIdxName = `idx_timeseries_${table}_${colName}`.replace(/"/g, '""');
      return `CREATE INDEX IF NOT EXISTS "${tsIdxName}" ON "${t}" ("${c}");`;
    }
    const idxName = `idx_${table}_${colName}`.replace(/"/g, '""');
    return `CREATE INDEX IF NOT EXISTS "${idxName}" ON "${t}" ("${c}");`;
  }

  compileCreateTableStatements(table: string, schema: TableSchema): [string, ...string[]] {
    const fragments: string[] = [];
    const statements: string[] = [];
    const indexedCols = new Set<string>();
    const searchableCols: string[] = [];

    for (const [colName, colBuilder] of Object.entries(schema)) {
      const def = colBuilder.def;
      fragments.push(this.compileColumnFragment(colName, def, "create"));

      if (def.isSearchable) searchableCols.push(colName);

      if ((def.isIndex || def.references) && !def.unique && !indexedCols.has(colName)) {
        indexedCols.add(colName);
        statements.push(this.compileIndexSql(table, colName, "plain"));
      }

      if (def.isTimeSeries) {
        if (!def.isIndex && !indexedCols.has(colName)) {
          indexedCols.add(colName);
          statements.push(this.compileIndexSql(table, colName, "timeseries"));
        }
      }
    }

    // The search vector is a generated column on the table itself, kept
    // in sync by Postgres on every write — the equivalent of the SQLite
    // FTS5 table, without a second table to maintain. The GIN index on
    // it is what the search query uses.
    if (searchableCols.length > 0) {
      fragments.push(
        `"${PGLITE_SEARCH_VECTOR_COLUMN}" tsvector GENERATED ALWAYS AS (${searchVectorExpression(searchableCols)}) STORED`,
      );
      statements.push(this.compileSearchIndexSql(table));
    }

    return [this.compileCreateTableSql(table, fragments), ...statements];
  }

  /** `CREATE INDEX … USING GIN` for a table's search-vector column. */
  compileSearchIndexSql(table: string): string {
    const t = table.replace(/"/g, '""');
    const idxName = `idx_${table}_fts`.replace(/"/g, '""');
    return `CREATE INDEX IF NOT EXISTS "${idxName}" ON "${t}" USING GIN ("${PGLITE_SEARCH_VECTOR_COLUMN}");`;
  }

  /**
   * Repair statements for a table whose search vector is missing (a
   * table created outside syncSchema, or an older database file): add
   * the generated column if absent, then the GIN index. Idempotent —
   * both statements are safe to run when the objects already exist.
   */
  compileSearchRepairStatements(table: string, schema: TableSchema): string[] {
    const searchableCols = Object.entries(schema)
      .filter(([, b]) => b.def.isSearchable)
      .map(([name]) => name);
    if (searchableCols.length === 0) return [];
    const t = table.replace(/"/g, '""');
    return [
      `ALTER TABLE "${t}" ADD COLUMN IF NOT EXISTS "${PGLITE_SEARCH_VECTOR_COLUMN}" tsvector GENERATED ALWAYS AS (${searchVectorExpression(searchableCols)}) STORED;`,
      this.compileSearchIndexSql(table),
    ];
  }

  compileLikePredicate(quotedCol: string, placeholder: string, escape: boolean): string {
    // Postgres LIKE is case-sensitive; SQLite's LIKE is ASCII
    // case-insensitive, so parity needs ILIKE on both branches.
    return escape ? `${quotedCol} ILIKE ${placeholder} ESCAPE '\\'` : `${quotedCol} ILIKE ${placeholder}`;
  }

  compileOrderNulls(dir: "ASC" | "DESC"): string {
    // Postgres defaults the opposite way to SQLite (ASC → NULLS LAST,
    // DESC → NULLS FIRST), so the ordering is stated explicitly to
    // match SQLite: ASC → NULLS FIRST, DESC → NULLS LAST.
    return dir === "ASC" ? " NULLS FIRST" : " NULLS LAST";
  }

  compileLimitOffset(take: number | undefined, skip: number | undefined): string {
    // Postgres rejects a negative LIMIT, so an unbounded read spells
    // `LIMIT ALL` where SQLite spells `LIMIT -1`. A bare OFFSET is
    // legal in Postgres, but LIMIT ALL keeps the shape identical.
    const limitSql =
      take !== undefined && take !== -1
        ? `LIMIT ${take}`
        : skip !== undefined
          ? "LIMIT ALL"
          : "";
    const offsetSql = skip !== undefined ? `OFFSET ${skip}` : "";
    return [limitSql, offsetSql].filter(Boolean).join(" ");
  }

  encodeParam(value: unknown, def?: ColumnDefinition): unknown {
    // Driver half of the old Table.serializeValue: the undefined/null
    // handling and the NOT NULL guard live in SqlCompiler.serializeValue,
    // which calls this after those checks. Postgres must NOT receive
    // boolean→1 (SQLite's encoding) — it takes real booleans.
    if (def?.isBoolean) return Boolean(value);
    if (def?.isJson) {
      return typeof value === "string" ? value : JSON.stringify(value);
    }
    if (value instanceof Date) return value.toISOString();
    if (typeof value === "boolean") return value;
    if (value instanceof Uint8Array) return value;
    // A structured value with no column definition (a raw-SQL caller, or a
    // column the schema does not declare) is stored as JSON, as before.
    // With a definition, the compiler rejects non-json objects before
    // this is reached.
    if (typeof value === "object" && value !== null) return JSON.stringify(value);
    return value;
  }

  decodeValue(value: unknown, def?: ColumnDefinition): unknown {
    // Driver half of the old Table.deserializeRow.
    if (value === null || value === undefined) return null;
    if (def?.isBoolean) {
      return !!value;
    }
    if (def?.isJson) {
      if (typeof value === "string") {
        try {
          return JSON.parse(value);
        } catch {
          /* leave as-is */
        }
      }
      // PGlite already parses JSONB into objects; pass those through.
      return value;
    }
    if (typeof value === "bigint") {
      // INT8 comes back as a number when it fits and a BigInt when it
      // does not (PGlite 0.6.0 default). A value past MAX_SAFE_INTEGER
      // cannot be a JS number without losing precision, so it throws
      // rather than silently corrupting an id or timestamp.
      if (value <= BigInt(Number.MAX_SAFE_INTEGER) && value >= BigInt(Number.MIN_SAFE_INTEGER)) {
        return Number(value);
      }
      throw new YattaError(`Postgres BIGINT value ${value} exceeds JS safe integer precision.`);
    }
    if (value instanceof Date) {
      // TIMESTAMPTZ reads back as a JS Date; the ORM's timestamp
      // columns hold toISOString() strings, so normalize to that.
      return value.toISOString();
    }
    return value;
  }

  compileUpsert(_plan: UpsertPlan): CompiledSql | null {
    // No atomic upsert: the core uses the transactional
    // find-first-then-update/insert fallback, which is the current
    // behaviour for SQLite too. An ON CONFLICT path is a later
    // optimisation.
    return null;
  }
}

/** Shared Postgres dialect instance (stateless — one per process). */
export const postgresDialect: SqlDialect = new PostgresDialect();
